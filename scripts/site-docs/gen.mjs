#!/usr/bin/env node
/**
 * Docs projection for the project page (issue #277).
 *
 * The repository keeps ONE copy of each document — the Markdown under `docs/`
 * and the root (`CONTRIBUTING.md`). This script projects the reading set into
 * `site/docs/*.html` so a reader who arrives at the page never bounces to
 * github.com to read a document, and reads it in the page's own type system
 * instead of GitHub's.
 *
 * Invariants:
 *
 *   A. NOTHING generated is committed. `site/docs/` is gitignored: the output
 *      is a deploy artifact, regenerated from the same commit every time. A
 *      projection that is not in git cannot drift from its source.
 *   B. The set of documents is derived, not listed twice. The only hand-written
 *      data is (slug, source path) in DOCS below; the title comes from the H1
 *      and the blurb from the first paragraph. A missing source FAILS the run
 *      instead of silently shrinking the site.
 *   C. Links keep working. A link to a projected document becomes a local
 *      `.html`; any other local path becomes its GitHub URL. `#anchors` are
 *      produced by github-slugger, the same algorithm GitHub uses, so anchors
 *      written against the repository keep resolving.
 *   D. No runtime. The output is static HTML + the shared `site/styles.css`;
 *      no `<script>`, no external asset (the page gate enforces both).
 *
 * Usage: node scripts/site-docs/gen.mjs
 * Then:  node scripts/site-check/check.mjs   (or: pnpm site)
 */
import { existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { marked } from "marked";
import { gfmHeadingId } from "marked-gfm-heading-id";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..", "..");
const SITE = path.join(ROOT, "site");
const OUT = path.join(SITE, "docs");
const REPO_URL = "https://github.com/ChristianLuciani/profile-as-code";
const SITE_URL = "https://christianluciani.github.io/profile-as-code";

/** The reading set. Order is the prev/next order on the docs index. */
const DOCS = [
  { slug: "user-guide", file: "docs/USER-GUIDE.md" },
  { slug: "spec", file: "docs/SPEC.md" },
  { slug: "contributing", file: "CONTRIBUTING.md" },
  { slug: "roadmap", file: "docs/ROADMAP.md" },
];

const GEN_NOTE =
  "AUTO-GENERATED by scripts/site-docs/gen.mjs — DO NOT EDIT. " +
  "Source: the Markdown file named below. Regenerate: pnpm site. " +
  "Not committed (site/docs/ is gitignored): this file is a deploy artifact, projected from one commit.";

marked.use(gfmHeadingId());

// --- markdown ---------------------------------------------------------------

function stripFrontmatter(md) {
  if (!md.startsWith("---\n")) return md;
  const end = md.indexOf("\n---\n", 4);
  return end === -1 ? md : md.slice(end + 5);
}

function decodeEntities(text) {
  return text
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, "&");
}

function plainText(html) {
  return decodeEntities(html.replace(/<[^>]+>/g, ""))
    .replace(/\s+/g, " ")
    .trim();
}

/** Cut at a word boundary and mark the cut, so a card never ends mid-word. */
function truncate(text, max) {
  if (text.length <= max) return text;
  const cut = text.slice(0, max);
  const space = cut.lastIndexOf(" ");
  return `${(space > max * 0.6 ? cut.slice(0, space) : cut).replace(/[\s,;:.—-]+$/, "")}…`;
}

function escapeHtml(text) {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function firstHeading(html) {
  const match = html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i);
  return match ? plainText(match[1]) : "";
}

function firstParagraph(html) {
  // Skip the H1 and any blockquote: a document's subtitle is metadata, not the
  // one-sentence description a reader (or a crawler) needs.
  const body = html
    .replace(/^[\s\S]*?<h1[^>]*>[\s\S]*?<\/h1>/i, "")
    .replace(/<blockquote>[\s\S]*?<\/blockquote>/gi, "");
  const match = body.match(/<p>([\s\S]*?)<\/p>/i);
  return match ? plainText(match[1]) : "";
}

// --- links ------------------------------------------------------------------

function isAbsolute(href) {
  return /^(?:[a-z][a-z0-9+.-]*:|\/\/|#)/i.test(href);
}

/**
 * Rewrite every local link: a projected document becomes a local page, any
 * other repository path becomes its GitHub URL. Returns the href unchanged when
 * it is already absolute (https, mailto, an in-page anchor).
 */
function rewriteHref(href, doc) {
  if (href === "" || isAbsolute(href)) return href;

  const hashIndex = href.indexOf("#");
  const target = hashIndex === -1 ? href : href.slice(0, hashIndex);
  const hash = hashIndex === -1 ? "" : href.slice(hashIndex);
  if (target === "") return href;

  const absolute = path.resolve(ROOT, path.dirname(doc.file), target);
  const relative = path.relative(ROOT, absolute).split(path.sep).join("/");

  const projected = DOCS.find((d) => d.file === relative);
  if (projected) return `./${projected.slug}.html${hash}`;

  const inRepo = !relative.startsWith("..") && !path.isAbsolute(relative);
  if (!inRepo || !existsSync(absolute)) {
    // A link the repository cannot resolve is left alone; `site-check` reports
    // it if it also fails to resolve inside site/.
    return href;
  }

  const kind = statSync(absolute).isDirectory() ? "tree" : "blob";
  return `${REPO_URL}/${kind}/main/${relative}${hash}`;
}

function rewriteLinks(html, doc) {
  return html
    .replace(/(\shref=")([^"]*)(")/g, (_m, open, href, close) => {
      return `${open}${escapeHtml(rewriteHref(decodeEntities(href), doc))}${close}`;
    })
    .trimEnd();
}

// --- shell ------------------------------------------------------------------

const MARK = `<svg class="mark" width="28" height="28" viewBox="0 0 32 32" aria-hidden="true" focusable="false">
          <defs>
            <mask id="pasco-cut">
              <rect width="32" height="32" fill="#fff"/>
              <path fill="#000" fill-rule="evenodd" d="M9.2 8A2 2 0 0 1 11.2 6H13.2A6.8 6.8 0 1 1 13.2 16.384V22.4A2 2 0 0 1 9.2 22.4Z M17.6 7.76a3.44 3.44 0 1 0 0 6.88 3.44 3.44 0 1 0 0-6.88Z"/>
              <circle cx="16.6" cy="10.2" r="1.15" fill="#000"/>
              <path d="M16.4 20.6c.9 1.8 2.2 2.7 3.7 2.7s2.8-.9 3.7-2.7" fill="none" stroke="#000" stroke-width="1.6" stroke-linecap="round"/>
            </mask>
          </defs>
          <circle cx="16" cy="16" r="13" fill="currentColor" mask="url(#pasco-cut)"/>
        </svg>`;

const NAV = `<nav class="site-nav" aria-label="Primary">
        <a href="../#what">What it does</a>
        <a href="../#on-ramps">On-ramps</a>
        <a href="../#status">Status</a>
        <a href="./" aria-current="page">Docs</a>
        <a class="nav-github" href="${REPO_URL}">GitHub <span aria-hidden="true">↗</span></a>
      </nav>`;

function releaseLine() {
  const released = process.env.SITE_RELEASED_AT;
  if (!released) return "";
  return `<p class="doc-release">Published from <code>${escapeHtml(released)}</code>: this page describes the released artifact, not <code>main</code>.</p>\n`;
}

function shell({ title, description, canonical, body, prefix = "../" }) {
  // A document title that already names the project does not get the suffix twice.
  const fullTitle = /profile-as-code/i.test(title) ? title : `${title} — profile-as-code`;
  return `<!-- ${GEN_NOTE} -->
<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escapeHtml(fullTitle)}</title>
  <meta name="description" content="${escapeHtml(description)}">
  <meta name="color-scheme" content="light dark">
  <link rel="canonical" href="${canonical}">
  <meta property="og:type" content="article">
  <meta property="og:title" content="${escapeHtml(fullTitle)}">
  <meta property="og:description" content="${escapeHtml(description)}">
  <meta property="og:url" content="${canonical}">
  <meta name="twitter:card" content="summary">
  <link rel="icon" href="${prefix}brand/mark-tile.svg" type="image/svg+xml">
  <link rel="stylesheet" href="${prefix}styles.css">
</head>
<body>
  <a class="skip-link" href="#main">Skip to content</a>

  <header class="site-header">
    <div class="wrap header-inner">
      <a class="brand" href="${prefix}" aria-label="profile-as-code — home">
        ${MARK}
        <span>profile-as-code</span>
      </a>
      ${NAV}
    </div>
  </header>

  <main id="main">
${body}
  </main>

  <footer class="site-footer">
    <div class="wrap footer-inner">
      <p><strong>profile-as-code</strong> — your professional identity, as code.</p>
      ${releaseLine()}      <p class="footer-meta">MIT code · <a href="${REPO_URL}/blob/main/TRADEMARK.md">marks reserved</a> · pre-1.0 · <a href="${REPO_URL}">GitHub</a></p>
    </div>
  </footer>
</body>
</html>
`;
}

// --- pages ------------------------------------------------------------------

function toc(html) {
  const items = [];
  for (const match of html.matchAll(/<h([23])\s+id="([^"]+)"[^>]*>([\s\S]*?)<\/h\1>/gi)) {
    const [, level, id, label] = match;
    items.push({ level: Number(level), id, label: plainText(label) });
  }
  if (items.length === 0) return "";
  const links = items
    .map(
      (item) =>
        `        <li class="lvl${item.level}"><a href="#${item.id}">${escapeHtml(item.label)}</a></li>`,
    )
    .join("\n");
  return `<nav class="doc-toc" aria-label="On this page">
        <p class="kicker">On this page</p>
        <ul>
${links}
        </ul>
      </nav>`;
}

function docNav(index, docs) {
  const previous = docs[index - 1];
  const next = docs[index + 1];
  const link = (target, rel, label) =>
    target
      ? `<a class="doc-${rel}" href="./${target.slug}.html" rel="${rel}"><span>${rel === "prev" ? "← " : ""}${label}${rel === "next" ? " →" : ""}</span><strong>${escapeHtml(target.title)}</strong></a>`
      : "";
  return `<nav class="doc-nav" aria-label="Documentation">
          ${link(previous, "prev", "Previous")}
          ${link(next, "next", "Next")}
        </nav>`;
}

function renderDoc(doc, index, docs) {
  const rendered = rewriteLinks(marked.parse(doc.raw, { gfm: true }), doc);
  const title = firstHeading(rendered);
  if (!title) throw new Error(`projected document has no H1 title: ${doc.file}`);
  const description = truncate(firstParagraph(rendered), 200);
  const onThisPage = toc(rendered);

  const body = `    <div class="wrap doc-layout">
      ${onThisPage}
      <article class="doc-body">
        <p class="doc-breadcrumb"><a href="./">Docs</a> <span aria-hidden="true">/</span> <span>${escapeHtml(title)}</span></p>
        <p class="doc-source">Source: <code>${doc.file}</code> — the page is a projection of it.</p>
${rendered}
        ${docNav(index, docs)}
      </article>
    </div>`;

  return shell({
    title,
    description,
    canonical: `${SITE_URL}/docs/${doc.slug}.html`,
    body,
  });
}

function renderIndex(docs) {
  const cards = docs
    .map(
      (doc) =>
        `        <li><a href="./${doc.slug}.html"><span>${escapeHtml(doc.title)}</span><small>${escapeHtml(doc.blurb)}</small></a></li>`,
    )
    .join("\n");
  const body = `    <div class="wrap doc-layout doc-layout-single">
      <article class="doc-body">
        <p class="doc-breadcrumb"><a href="../">Home</a> <span aria-hidden="true">/</span> <span>Docs</span></p>
        <h1>Documentation</h1>
        <p class="lede">The same documents that live in the repository, projected into this page's type system. Each one names its source file; the repository stays the only copy that is edited.</p>
        <ul class="doc-links">
${cards}
        </ul>
      </article>
    </div>`;
  return shell({
    title: "Documentation",
    description:
      "The profile-as-code documents: user guide, specification, contributing guide, and roadmap.",
    canonical: `${SITE_URL}/docs/`,
    body,
  });
}

// --- main -------------------------------------------------------------------

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

// Title and blurb are derived from the source, never listed twice: prev/next
// labels need every title before the first page can be rendered.
const docs = DOCS.map((doc) => {
  const source = path.join(ROOT, doc.file);
  if (!existsSync(source)) {
    throw new Error(`projected document does not exist: ${doc.file} (declared in DOCS)`);
  }
  const raw = stripFrontmatter(readFileSync(source, "utf8"));
  const rendered = marked.parse(raw, { gfm: true });
  const title = firstHeading(rendered);
  if (!title) throw new Error(`projected document has no H1 title: ${doc.file}`);
  return { ...doc, raw, title, blurb: truncate(firstParagraph(rendered), 140) };
});

for (const [index, doc] of docs.entries()) {
  writeFileSync(path.join(OUT, `${doc.slug}.html`), renderDoc(doc, index, docs));
}
writeFileSync(path.join(OUT, "index.html"), renderIndex(docs));

console.log(
  `site-docs: wrote ${docs.length + 1} page(s) to ${path.relative(ROOT, OUT)}/ ` +
    `(${docs.map((d) => d.slug).join(", ")}, index)`,
);
