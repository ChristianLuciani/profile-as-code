/** `prefix` is the path back to `site/` — `../` from `docs/`, empty at the root. */
function nav(prefix) {
  // `./#what` (not `#what`) at the root: the 404 is its own page, so an
  // in-page anchor there would point at ids the page does not have.
  const root = prefix === "" ? "./" : prefix;
  return `<nav class="site-nav" aria-label="Primary">
        <a href="${root}#what">What it does</a>
        <a href="${root}#on-ramps">On-ramps</a>
        <a href="${root}#status">Status</a>
        <a href="${prefix}docs/"${prefix === "../" ? ' aria-current="page"' : ""}>Docs</a>
        <a class="nav-github" href="${REPO_URL}">GitHub <span aria-hidden="true">↗</span></a>
      </nav>`;
}

function releaseLine() {
  const released = process.env.SITE_RELEASED_AT;
  if (!released) return "";
  return `<p class="doc-release">Published from <code>${escapeHtml(released)}</code>: this page describes the released artifact, not <code>main</code>.</p>\n`;
}

/** A JSON-LD block. `type` is data, not code: the page gate allows exactly this
 * script type and nothing else. `<` is escaped so a string cannot close the tag. */
function jsonLdTag(data) {
  return `<script type="application/ld+json">${JSON.stringify(data).replace(/</g, "\\u003c")}</script>`;
}

function ogTags() {
  if (!SITE.ogImage) return "";
  const url = `${SITE_URL}/${SITE.ogImage.path}`;
  return `<meta property="og:image" content="${url}">
  <meta property="og:image:width" content="${SITE.ogImage.width}">
  <meta property="og:image:height" content="${SITE.ogImage.height}">
  <meta property="og:image:alt" content="${escapeHtml(SITE.ogImage.alt)}">`;
}

function shell({
  title,
  description,
  canonical,
  body,
  prefix = "../",
  jsonLd = [],
  noindex = false,
  ogType = "article",
}) {
  // A document title that already names the project does not get the suffix twice.
  const fullTitle = /profile-as-code/i.test(title) ? title : `${title} — profile-as-code`;
  return `<!-- ${GEN_NOTE} -->
<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escapeHtml(fullTitle)}</title>
  <meta name="description" content="${escapeHtml(description)}">
  <meta name="color-scheme" content="light dark">
  ${canonical ? `<link rel="canonical" href="${canonical}">` : ""}
  ${noindex ? '<meta name="robots" content="noindex">' : ""}
  <meta property="og:type" content="${ogType}">
  <meta property="og:site_name" content="${SITE.name}">
  <meta property="og:title" content="${escapeHtml(fullTitle)}">
  <meta property="og:description" content="${escapeHtml(description)}">
  ${canonical ? `<meta property="og:url" content="${canonical}">` : ""}
  ${ogTags()}
  <meta name="twitter:card" content="${SITE.ogImage ? "summary_large_image" : "summary"}">
  ${jsonLd.map(jsonLdTag).join("\n  ")}
  <link rel="icon" href="${prefix}brand/mark-tile.svg" type="image/svg+xml">
  <link rel="stylesheet" href="${prefix}styles.css">
</head>
<body>
  <a class="skip-link" href="#main">Skip to content</a>

  <header class="site-header">
    <div class="wrap header-inner">
      <a class="brand" href="${prefix}" aria-label="profile-as-code — home">
        ${MARK}
        <span>profile-as-code</span>
      </a>
      ${nav(prefix)}
    </div>
  </header>

  <main id="main">
${body}
  </main>

  <footer class="site-footer">
    <div class="wrap footer-inner">
      <p><strong>profile-as-code</strong> — your professional identity, as code.</p>
      ${releaseLine()}      <p class="footer-meta">MIT code · <a href="${REPO_URL}/blob/main/TRADEMARK.md">marks reserved</a> · pre-1.0 · <a href="${REPO_URL}">GitHub</a></p>
    </div>
  </footer>
</body>
</html>
`;
}

// --- pages ------------------------------------------------------------------

function toc(html) {
  const items = [];
  for (const match of html.matchAll(/<h([23])\s+id="([^"]+)"[^>]*>([\s\S]*?)<\/h\1>/gi)) {
    const [, level, id, label] = match;
    items.push({ level: Number(level), id, label: plainText(label) });
  }
  if (items.length === 0) return "";
  const links = items
    .map(
      (item) =>
        `        <li class="lvl${item.level}"><a href="#${item.id}">${escapeHtml(item.label)}</a></li>`,
    )
    .join("\n");
  return `<nav class="doc-toc" aria-label="On this page">
        <p class="kicker">On this page</p>
        <ul>
${links}
        </ul>
      </nav>`;
}

function docNav(index, docs) {
  const previous = docs[index - 1];
  const next = docs[index + 1];
  const link = (target, rel, label) =>
    target
      ? `<a class="doc-${rel}" href="./${target.slug}.html" rel="${rel}"><span>${rel === "prev" ? "← " : ""}${label}${rel === "next" ? " →" : ""}</span><strong>${escapeHtml(target.title)}</strong></a>`
      : "";
  return `<nav class="doc-nav" aria-label="Documentation">
          ${link(previous, "prev", "Previous")}
          ${link(next, "next", "Next")}
        </nav>`;
}

function renderDoc(doc, index, docs) {
  const rendered = rewriteLinks(wrapTables(marked.parse(doc.raw, { gfm: true })), doc);
  const title = firstHeading(rendered);
  if (!title) throw new Error(`projected document has no H1 title: ${doc.file}`);
  const description = truncate(firstParagraph(rendered), 200);
  const onThisPage = toc(rendered);
  const updated = lastModified(doc.file);
  const canonical = `${SITE_URL}/docs/${doc.slug}.html`;
  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "TechArticle",
    headline: title,
    description,
    url: canonical,
    ...(updated ? { dateModified: updated } : {}),
    isPartOf: { "@type": "WebSite", name: SITE.name, url: `${SITE_URL}/` },
  };

  const body = `    <div class="wrap doc-layout">
      ${onThisPage}
      <article class="doc-body"${doc.lang === "en" ? "" : ` lang="${doc.lang}"`}>
        <p class="doc-breadcrumb"><a href="./">Docs</a> <span aria-hidden="true">/</span> <span>${escapeHtml(title)}</span></p>
        <p class="doc-source">Source: <code>${doc.file}</code> — the page is a projection of it.${updated ? ` Updated <time datetime="${updated}">${day(updated)}</time>.` : ""}</p>
${rendered}
        ${docNav(index, docs)}
      </article>
    </div>`;

  return shell({ title, description, canonical, body, jsonLd: [jsonLd] });
}

function renderIndex(docs) {
  const cards = docs
    .map(
      (doc) =>
        `        <li><a href="./${doc.slug}.html"><span>${escapeHtml(doc.title)}</span><small>${escapeHtml(doc.blurb)}</small></a></li>`,
    )
    .join("\n");
  const body = `    <div class="wrap doc-layout doc-layout-single">
      <article class="doc-body">
        <p class="doc-breadcrumb"><a href="../">Home</a> <span aria-hidden="true">/</span> <span>Docs</span></p>
        <h1>Documentation</h1>
        <p class="lede">The same documents that live in the repository, projected into this page's type system. Each one names its source file; the repository stays the only copy that is edited.</p>
        <ul class="doc-links">
${cards}
        </ul>
      </article>
    </div>`;
  return shell({
    title: "Documentation",
    description:
      "The profile-as-code documents: user guide, specification, contributing guide, and roadmap.",
    canonical: `${SITE_URL}/docs/`,
    body,
  });
}

// --- site-root artifacts ----------------------------------------------------

function buildNotFound() {
  const body = `    <div class="wrap doc-layout doc-layout-single">
      <article class="doc-body">
        <p class="doc-breadcrumb"><a href="./">Home</a></p>
        <h1>Page not found</h1>
        <p class="lede">That URL does not exist on this site — the documentation index lists everything that does.</p>
        <ul class="checks">
          <li><a href="./docs/">Documentation index</a></li>
          <li><a href="./">Home</a></li>
          <li><a href="${REPO_URL}">The repository</a></li>
        </ul>
      </article>
    </div>`;
  return shell({
    title: "Page not found",
    description: "That URL does not exist on the profile-as-code site.",
    canonical: null,
    body,
    prefix: "",
    noindex: true,
    ogType: "website",
  });
}

function buildSitemap(entries) {
  const urls = entries
    .map(
      ({ loc, lastmod }) =>
        `  <url>\n    <loc>${loc}</loc>${lastmod ? `\n    <lastmod>${lastmod.slice(0, 10)}</lastmod>` : ""}\n  </url>`,
    )
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;
}

/**
 * `robots.txt` is host-scoped (RFC 9309): for a project site served under
 * `/<repo>/` crawlers never fetch this file. It ships anyway — it becomes
 * correct the day a custom domain exists, and it costs nothing.
 */
function buildRobots() {
  return `# Project site: robots.txt is host-scoped (RFC 9309). Effective once a
# custom domain serves this site at the host root.
User-agent: *
Allow: /

Sitemap: ${SITE_URL}/sitemap.xml
`;
}

function h2Anchors(html) {
  return [...html.matchAll(/<h2\s+id="([^"]+)"[^>]*>([\s\S]*?)<\/h2>/gi)].map(([, id, label]) => ({
    id,
    label: plainText(label),
  }));
}

function buildLlmsTxt(docs) {
  const outlines = docs
    .map((doc) => {
      const sections = h2Anchors(doc.rendered);
      const lines = sections
        .map((s) => `- [${s.label}](${SITE_URL}/docs/${doc.slug}.html#${s.id})`)
        .join("\n");
      return `## ${doc.title}\n\n- [Full document](${SITE_URL}/docs/${doc.slug}.html): ${doc.blurb}\n${lines}\n`;
    })
    .join("\n");

  return `# ${SITE.name}

> ${SITE.tagline} The documentation below is projected from the repository (${REPO_URL}) at deploy time — the repository is the source of truth; this site is a projection of it.

## Documentation

- [Documentation index](${SITE_URL}/docs/): every projected document.
${docs.map((doc) => `- [${doc.title}](${SITE_URL}/docs/${doc.slug}.html): ${doc.blurb}`).join("\n")}

${outlines}
## About this site

- [AGENTS.md](${SITE_URL}/AGENTS.md): guide for an agent consuming this site.
- [Source repository](${REPO_URL}): canonical; every page here is generated (never edit a generated file).
`;
}

function buildSiteAgents(docs) {
  return `# AGENTS.md — the project site

This is the published surface of ${SITE.name}. If you are an agent consuming it,
read this file first.

## Source of truth

- The repository is canonical: ${REPO_URL}.
- Every page under this site is **projected from the repository at deploy time**
  and is not committed. Editing the site edits nothing.

## How to consume

- [\`llms.txt\`](${SITE_URL}/llms.txt): index of this site — summary, documents and section anchors.
- [Documentation index](${SITE_URL}/docs/): the projected documents in one place.
${docs.map((doc) => `- [${doc.title}](${SITE_URL}/docs/${doc.slug}.html) — source: \`${doc.file}\``).join("\n")}

## What answers what

| Question | Read |
|---|---|
| How do I use the CLI? | the user guide |
| What is the contract (data model, decisions)? | the specification |
| How do I contribute, and what gates run? | the contributing guide |
| What is planned and what shipped? | the roadmap |

## Rules

- A version claim appears in the form \`${SITE.claimPackage}@<version>\` and must
  match \`${SITE.versionManifest}\`; the release fails otherwise.
- Anchors are identical to GitHub's, so a citation works on both surfaces.
- Nothing here executes JavaScript (JSON-LD is data).
`;
}

// --- main -------------------------------------------------------------------

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

// Title and blurb are derived from the source, never listed twice: prev/next
// labels need every title before the first page can be rendered.
const docs = DOCS.map((doc) => {
  const source = path.join(ROOT, doc.file);
  if (!existsSync(source)) {
    throw new Error(`projected document does not exist: ${doc.file} (declared in DOCS)`);
  }
  const raw = stripFrontmatter(readFileSync(source, "utf8"));
  const rendered = marked.parse(raw, { gfm: true });
  const title = firstHeading(rendered);
  if (!title) throw new Error(`projected document has no H1 title: ${doc.file}`);
  return { ...doc, raw, rendered, title, blurb: truncate(firstParagraph(rendered), 140) };
});

for (const [index, doc] of docs.entries()) {
  writeFileSync(path.join(OUT, `${doc.slug}.html`), renderDoc(doc, index, docs));
}
writeFileSync(path.join(OUT, "index.html"), renderIndex(docs));

// --- site root: 404, sitemap, robots, llms.txt, AGENTS.md -------------------

const mostRecent = (dates) => dates.filter(Boolean).sort().pop() ?? null;
const docsUpdated = mostRecent(docs.map((doc) => lastModified(doc.file)));
const entries = [
  { loc: `${SITE_URL}/`, lastmod: lastModified("site/index.html") },
  { loc: `${SITE_URL}/docs/`, lastmod: docsUpdated },
  ...docs.map((doc) => ({
    loc: `${SITE_URL}/docs/${doc.slug}.html`,
    lastmod: lastModified(doc.file),
  })),
];

const sitemap = buildSitemap(entries);
const llms = buildLlmsTxt(docs);
const robots = buildRobots();
const notFound = buildNotFound();
const siteAgents = buildSiteAgents(docs);

// Structural assertions before anything is written: a malformed sitemap or a
// document missing from llms.txt is a silent hole, not a cosmetic bug.
const sitemapLocs = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]);
if (sitemapLocs.length !== entries.length) {
  throw new Error(`sitemap has ${sitemapLocs.length} loc(s) for ${entries.length} page(s)`);
}
for (const loc of sitemapLocs) {
  if (!loc.startsWith(`${SITE_URL}/`)) throw new Error(`sitemap loc outside the site: ${loc}`);
}
for (const doc of docs) {
  if (!llms.includes(`/docs/${doc.slug}.html`)) {
    throw new Error(`llms.txt does not list ${doc.slug}`);
  }
  if (!siteAgents.includes(`/docs/${doc.slug}.html`)) {
    throw new Error(`AGENTS.md does not list ${doc.slug}`);
  }
}
if (!robots.includes(`Sitemap: ${SITE_URL}/sitemap.xml`))
  throw new Error("robots.txt lost its sitemap");
if (!/name="robots" content="noindex"/.test(notFound))
  throw new Error("404.html must not be indexed");

writeFileSync(path.join(SITE_DIR, "404.html"), notFound);
writeFileSync(path.join(SITE_DIR, "sitemap.xml"), sitemap);
writeFileSync(path.join(SITE_DIR, "robots.txt"), robots);
writeFileSync(path.join(SITE_DIR, "llms.txt"), llms);
writeFileSync(path.join(SITE_DIR, "AGENTS.md"), siteAgents);

console.log(
  `site-docs: ${docs.length + 1} page(s) + 404, sitemap (${entries.length} url), robots, ` +
    `llms.txt, AGENTS.md → ${path.relative(ROOT, SITE_DIR)}/ ` +
    `(${docs.map((d) => d.slug).join(", ")}, index)`,
);
