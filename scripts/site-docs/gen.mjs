#!/usr/bin/env node
/**
 * Docs projection for the project page (issue #277).
 *
 * The repository keeps ONE copy of each document — the Markdown under `docs/`
 * and the root (`CONTRIBUTING.md`). This script projects the reading set into
 * `site/docs/*.html` so a reader who arrives at the page never bounces to
 * github.com to read a document, and reads it in the page's own type system
 * instead of GitHub's.
 *
 * Invariants:
 *
 *   A. NOTHING generated is committed. `site/docs/` is gitignored: the output
 *      is a deploy artifact, regenerated from the same commit every time. A
 *      projection that is not in git cannot drift from its source.
 *   B. The set of documents is derived, not listed twice. The only hand-written
 *      data is (slug, source path) in DOCS below; the title comes from the H1
 *      and the blurb from the first paragraph. A missing source FAILS the run
 *      instead of silently shrinking the site.
 *   C. Links keep working. A link to a projected document becomes a local
 *      `.html`; any other local path becomes its GitHub URL. `#anchors` are
 *      produced by github-slugger, the same algorithm GitHub uses, so anchors
 *      written against the repository keep resolving.
 *   D. No runtime. The output is static HTML + the shared `site/styles.css`;
 *      no `<script>`, no external asset (the page gate enforces both).
 *
 * Usage: node scripts/site-docs/gen.mjs
 * Then:  node scripts/site-check/check.mjs   (or: pnpm site)
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { marked } from "marked";
import { gfmHeadingId } from "marked-gfm-heading-id";
/** Site config + reading set: one home, also what the release barrier scans. */
import { DOCS, SITE } from "./site-config.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..", "..");
const SITE_DIR = path.join(ROOT, "site");
const OUT = path.join(SITE_DIR, "docs");
const REPO_URL = `https://github.com/${SITE.repo}`;
// The ref the page is published from (`SITE_REF` = the release commit). A link
// to a document that is NOT projected must land on the same tree, or the reader
// gets unreleased content from `main`.
const SITE_REF = process.env.SITE_REF || "main";
const SITE_URL = SITE.baseUrl;

const GEN_NOTE =
  "AUTO-GENERATED by scripts/site-docs/gen.mjs — DO NOT EDIT. " +
  "Source: the Markdown file named below. Regenerate: pnpm site. " +
  "Not committed (site/docs/ is gitignored): this file is a deploy artifact, projected from one commit.";

marked.use(gfmHeadingId());

// --- dates ------------------------------------------------------------------

let shallow;
/** A shallow clone cannot answer "when did THIS file change": `git log -1` then
 * returns HEAD's date, which is a lie. Return null and omit the date instead. */
function isShallow() {
  if (shallow !== undefined) return shallow;
  try {
    shallow =
      execFileSync("git", ["rev-parse", "--is-shallow-repository"], {
        cwd: ROOT,
        encoding: "utf8",
      }).trim() === "true";
  } catch {
    shallow = true;
  }
  return shallow;
}

/** `lastmod` for a path: full ISO date of its last commit, or null. */
function lastModified(file) {
  if (isShallow()) return null;
  try {
    const iso = execFileSync("git", ["log", "-1", "--format=%cI", "--", file], {
      cwd: ROOT,
      encoding: "utf8",
    }).trim();
    return iso || null;
  } catch {
    return null;
  }
}

const day = (iso) => (iso ? iso.slice(0, 10) : "");

// --- markdown ---------------------------------------------------------------

function stripFrontmatter(md) {
  if (!md.startsWith("---\n")) return md;
  const end = md.indexOf("\n---\n", 4);
  return end === -1 ? md : md.slice(end + 5);
}

function decodeEntities(text) {
  return text
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, "&");
}

function plainText(html) {
  return decodeEntities(html.replace(/<[^>]+>/g, ""))
    .replace(/\s+/g, " ")
    .trim();
}

/** Cut at a word boundary and mark the cut, so a card never ends mid-word. */
function truncate(text, max) {
  if (text.length <= max) return text;
  const cut = text.slice(0, max);
  const space = cut.lastIndexOf(" ");
  return `${(space > max * 0.6 ? cut.slice(0, space) : cut).replace(/[\s,;:.—-]+$/, "")}…`;
}

function escapeHtml(text) {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function firstHeading(html) {
  const match = html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i);
  return match ? plainText(match[1]) : "";
}

function firstParagraph(html) {
  // Skip the H1 and any blockquote: a document's subtitle is metadata, not the
  // one-sentence description a reader (or a crawler) needs.
  const body = html
    .replace(/^[\s\S]*?<h1[^>]*>[\s\S]*?<\/h1>/i, "")
    .replace(/^\s*<blockquote>[\s\S]*?<\/blockquote>/i, "");
  const match = body.match(/<p>([\s\S]*?)<\/p>/i);
  return match ? plainText(match[1]) : "";
}

// --- links ------------------------------------------------------------------

function isAbsolute(href) {
  return /^(?:[a-z][a-z0-9+.-]*:|\/\/|#)/i.test(href);
}

/**
 * Rewrite every local link: a projected document becomes a local page, any
 * other repository path becomes its GitHub URL. Returns the href unchanged when
 * it is already absolute (https, mailto, an in-page anchor).
 */
function rewriteHref(href, doc) {
  if (href === "" || isAbsolute(href)) return href;

  const hashIndex = href.indexOf("#");
  const target = hashIndex === -1 ? href : href.slice(0, hashIndex);
  const hash = hashIndex === -1 ? "" : href.slice(hashIndex);
  if (target === "") return href;

  const absolute = path.resolve(ROOT, path.dirname(doc.file), target);
  const relative = path.relative(ROOT, absolute).split(path.sep).join("/");

  const projected = DOCS.find((d) => d.file === relative);
  if (projected) return `./${projected.slug}.html${hash}`;

  const inRepo = !relative.startsWith("..") && !path.isAbsolute(relative);
  if (!inRepo || !existsSync(absolute)) {
    // A link the repository cannot resolve is left alone; `site-check` reports
    // it if it also fails to resolve inside site/.
    return href;
  }

  const kind = statSync(absolute).isDirectory() ? "tree" : "blob";
  return `${REPO_URL}/${kind}/${SITE_REF}/${relative}${hash}`;
}

/** Keep table semantics (a11y) and move the horizontal scroll to a wrapper. */
function wrapTables(html) {
  return html
    .replace(/<table>/g, '<div class="md-table"><table>')
    .replace(/<\/table>/g, "</table></div>");
}

function rewriteLinks(html, doc) {
  return html
    .replace(/(\shref=")([^"]*)(")/g, (_m, open, href, close) => {
      return `${open}${escapeHtml(rewriteHref(decodeEntities(href), doc))}${close}`;
    })
    .trimEnd();
}

