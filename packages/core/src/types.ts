/** Every drift finding is a warning (D12): facts warn, schema fails. */
export interface Issue {
  /** Stable machine-readable code, e.g. `drift/date-range-inverted`. */
  code: string;
  /** Always `warn` in v1 (D12). Reserved so a future `error` severity can be added without breaking consumers. */
  severity: 'warn';
  /** Human-readable explanation in EN (docs convention, D8). */
  message: string;
  /** Dot-path into the profile where the problem lives, e.g. `experience[1]`. */
  path: string;
  /** Platform(s) involved, when the issue is cross-surface. */
  surfaces?: Platform[];
}

/** One scored, weighted GEO check (see `geoCheck`). */
export interface GeoCheck {
  code: string;
  label: string;
  /** 0..1 — 1 = fully satisfied. */
  score: number;
  /** 0..1 — share of the total score this check contributes. */
  weight: number;
  detail: string;
}

export interface GeoSection {
  label: string;
  detail: string;
  checks: GeoCheck[];
  /** 0..100 for this section alone. */
  score: number;
}

export interface StructuredDataReadiness {
  /** schema.org entity emitted: `Person` (default) or `Organization` (brand flavor, D15/§17). */
  entityType: 'Person' | 'Organization';
  /** True when a schema.org JSON-LD can be emitted by the web renderer. */
  ready: boolean;
  /** Share of the considered fields that are populated (0..1). */
  completeness: number;
  fields: {
    name: boolean;
    sameAs: string[];
    image?: string;
    address?: string;
    jobTitle?: string;
    worksFor?: string;
    /** brand (Organization) */
    logo?: string;
    foundingDate?: string;
    slogan?: string;
    description?: string;
  };
  /** Ready-to-embed JSON-LD (web renderer consumes it). */
  jsonLd?: {
    '@context': 'https://schema.org';
    '@type': 'Person' | 'Organization';
    name: string;
    sameAs: string[];
    image?: string;
    address?: string;
    jobTitle?: string;
    worksFor?: string;
    logo?: string;
    foundingDate?: string;
    slogan?: string;
    description?: string;
    /** v1.4 (D17/§18.9): public credentials as EducationalOccupationalCredential
     *  (Person and Organization both carry hasCredential in schema.org). */
    hasCredential?: EducationalOccupationalCredentialLd[];
  };
}

/** schema.org EducationalOccupationalCredential emitted from a public credential (§18.9). */
export interface EducationalOccupationalCredentialLd {
  '@type': 'EducationalOccupationalCredential';
  name?: string;
  url?: string;
  awardedBy?: { '@type': 'Organization'; name: string };
  /** From `issued` (§18.2). */
  validFrom?: string;
  /** From `expires` (§18.2). */
  validThrough?: string;
}

export interface SemanticAssociationCoverage {
  /** The 3–5 anchors of positioning.geo.semanticAssociations. */
  anchors: string[];
  /** Anchors reinforced in at least one other surface (statement, skills, keywords, projects). */
  reinforced: string[];
  /** Anchors found nowhere else — they exist only in positioning.geo. */
  missing: string[];
  /** 0..1 — reinforced / total. */
  coverage: number;
}

export interface GeoReport {
  /** 0..100 — cross-cutting GEO readiness (report, not a gate; D7, §8). */
  score: number;
  sections: {
    factConsistency: GeoSection;
    /** Machine-readable schema.org Person readiness for the web renderer (M5). */
    structuredData: GeoSection & { readiness: StructuredDataReadiness };
    /** The 3–5 semantic anchors and how well they are reinforced across surfaces. */
    semanticAssociations: GeoSection & { anchors: SemanticAssociationCoverage };
    citability: GeoSection;
  };
  /** Flat list of every scored check (for `pasco validate` output). */
  checks: GeoCheck[];
}

/** The language-aware slice a renderer consumes (SPEC §7, compile()). */
export interface PlatformProfile {
  platform: Platform;
  lang: Lang;
  /** Workspace flavor (D15) — renderers branch on person vs brand surfaces. */
  flavor: Flavor;
  /** Facts — passed through untouched from the profile. */
  identity: Identity;
  experience: ExperienceItem[];
  projects: Project[];
  publications: Publication[];
  skills: Skill[];
  /** Language-aware text, filtered by platform+lang. */
  bios: Bio[];
  headlines: Headline[];
  statement?: string;
  audiences: Record<string, string>;
  citationsGoal?: string;
  /** SEO set for this platform + GEO associations/claims. */
  keywords: { seo: string[]; geo: { associations?: string[]; claims?: string[] } };
  /** Brand blocks (v1.1/§17) — pass through untouched, lang-filtered where textual. */
  socialHandles: SocialHandle[];
  newsletter?: Newsletter;
  podcast?: Podcast;
  press: PressItem[];
  brandAudiences: Record<string, string>;
  /** User checks targeting this platform (platform `all` included). */
  checks: NonNullable<Profile['checks']>;
  /** Evidence registry (v1.4/D17, §18) — facts, pass through untouched; renderers
   *  emit only `visibility: public` entries (§18.5). */
  credentials: Credential[];
  artifacts: Artifact[];
  active?: ActiveEntry;
  /** Dot-paths of langMaps that fell back to `en` because `lang` was absent. */
  fallbacks: string[];
}
