/** Every drift finding is a warning (D12): facts warn, schema fails. */
export interface Issue {
  /** Stable machine-readable code, e.g. `drift/date-range-inverted`. */
  code: string;
  /** Always `warn` in v1 (D12). Reserved so a future `error` severity can be added without breaking consumers. */
  severity: "warn";
  /** Human-readable explanation in EN (docs convention, D8). */
  message: string;
  /** Dot-path into the profile where the problem lives, e.g. `experience[1]`. */
  path: string;
  /** Platform(s) involved, when the issue is cross-surface. */
  surfaces?: Platform[];
}

/** One scored, weighted GEO check (see `geoCheck`). */
export interface GeoCheck {
  code: string;
  label: string;
  /** 0..1 — 1 = fully satisfied. */
  score: number;
  /** 0..1 — share of the total score this check contributes. */
  weight: number;
  /** SPEC §8 (#399): a code that has nothing to measure in this workspace.
   *  `applicable: false` is excluded from the weighted mean (and from its section's
   *  score) instead of scoring a sentinel; absent = applicable. The declared
   *  `weight` stays visible so a reader can see what the code would carry. */
  applicable?: boolean;
  detail: string;
  /** v1.10 (#289), additive: the reporting tier. Absent = `warn` (the pre-v1.10
   *  checks are all warnings). `info` NEVER changes the pass/fail story — a
   *  dormant profile is not a bad profile; the tier qualifies the way the
   *  consumer renders the finding, never the math. */
  severity?: "warn" | "info";
}

export interface GeoSection {
  label: string;
  detail: string;
  checks: GeoCheck[];
  /** 0..100 for this section alone. When `applicable` is false this is a
   *  placeholder (0), not a measurement — no code in the section can contribute
   *  weight. Absent = applicable (all current sections). */
  score: number;
  /** §8/#399: present and false when no code in the section can contribute
   *  weight (every code N/A, or every applicable code declares weight 0). The
   *  section then has no mean and contributes nothing to the overall. */
  applicable?: boolean;
}

export interface StructuredDataReadiness {
  /** schema.org entity emitted: `Person` (default) or `Organization` (brand flavor, D15/§17). */
  entityType: "Person" | "Organization";
  /** True when a schema.org JSON-LD can be emitted by the web renderer. */
  ready: boolean;
  /** Share of the considered fields that are populated (0..1). */
  completeness: number;
  fields: {
    name: boolean;
    sameAs: string[];
    /** v1.6 (#103): the canonical entity `@id` (the `role: identity` link), when declared. */
    id?: string;
    /** v1.5 (issue #71): the contact email (fact, schema.org `email`), when present. */
    email?: string;
    image?: string;
    address?: string;
    /** v1.13 (issue #334): the ISO 3166-1 alpha-2 nationality code. Populated on the
     *  Person branch only (a brand/Organization has no nationality, so the brand branch
     *  leaves it undefined). Informational — NOT in the completeness ratio. */
    nationality?: string;
    jobTitle?: string;
    worksFor?: string;
    /** brand (Organization) */
    logo?: string;
    foundingDate?: string;
    slogan?: string;
    description?: string;
  };
  /** Ready-to-embed JSON-LD (web renderer consumes it). */
  jsonLd?: {
    "@context": "https://schema.org";
    "@type": "Person" | "Organization";
    /** v1.6 (#103): the canonical entity identifier (SPEC §15.4), from the
     *  `role: identity` link. OPTIONAL by design (Option A): a workspace that declares no
     *  `role` still emits its JSON-LD, just without an anchor — suppressing the block
     *  would strip structured data from every pre-v1.6 workspace. */
    "@id"?: string;
    name: string;
    /** v1.5 (issue #71): the contact email (schema.org `email`) — emitted on both
     *  Person and Organization JSON-LD; declared here so the test type-check can
     *  read it (#181). */
    email?: string;
    sameAs: string[];
    image?: string;
    address?: string;
    /** v1.13 (issue #334): the Person `nationality` node — the alpha-2 code as
     *  `Country.identifier`. Person-only: a brand (Organization) has no nationality. */
    nationality?: { "@type": "Country"; identifier: string };
    jobTitle?: string;
    worksFor?: string;
    logo?: string;
    foundingDate?: string;
    slogan?: string;
    description?: string;
    /** v1.4 (D17/§18.9): public credentials as EducationalOccupationalCredential
     *  (Person and Organization both carry hasCredential in schema.org). */
    hasCredential?: EducationalOccupationalCredentialLd[];
  };
  /** v1.10 (issue #288, consumer half #316): the `FAQPage` node — a DIFFERENT
   *  schema.org @type than the entity, so it is its own field, never folded into
   *  `jsonLd`. Emitted iff root `faq[]` exists (never an empty FAQPage). No `@id`
   *  by design: the engine never invents an anchor (the same rule the entity node
   *  follows, §15.4), and a URL fragment convention is not a declared decision.
   *  A declared `faq[].source` travels as `Answer.citation` (schema.org `Answer`
   *  is a `CreativeWork`). */
  faqJsonLd?: {
    "@context": "https://schema.org";
    "@type": "FAQPage";
    mainEntity: Array<{
      "@type": "Question";
      name: string;
      acceptedAnswer: {
        "@type": "Answer";
        text: string;
        /** The declared pointer backing this answer (v1.10, #288/#316). */
        citation?: string;
      };
    }>;
  };
}

/** schema.org EducationalOccupationalCredential emitted from a public credential (§18.9). */
export interface EducationalOccupationalCredentialLd {
  "@type": "EducationalOccupationalCredential";
  name?: string;
  url?: string;
  awardedBy?: { "@type": "Organization"; name: string };
  /** From `issued` (§18.2). */
  validFrom?: string;
  /** From `expires` (§18.2). */
  validThrough?: string;
}

export interface SemanticAssociationCoverage {
  /** The 3–5 anchors of positioning.geo.semanticAssociations. */
  anchors: string[];
  /** Anchors reinforced in at least one other surface (statement, skills, keywords, projects). */
  reinforced: string[];
  /** Anchors found nowhere else — they exist only in positioning.geo. */
  missing: string[];
  /** 0..1 — reinforced / total. */
  coverage: number;
}

export interface GeoReport {
  /** 0..100 — cross-cutting GEO readiness (report, not a gate; D7, §8). */
  score: number;
  sections: {
    factConsistency: GeoSection;
    /** Machine-readable schema.org Person readiness for the web renderer (M5). */
    structuredData: GeoSection & { readiness: StructuredDataReadiness };
    /** The 3–5 semantic anchors and how well they are reinforced across surfaces. */
    semanticAssociations: GeoSection & { anchors: SemanticAssociationCoverage };
    citability: GeoSection;
  };
  /** Flat list of every scored check (for `pasco validate` output). */
  checks: GeoCheck[];
}

/** The language-aware slice a renderer consumes (SPEC §7, compile()). */
export interface PlatformProfile {
  platform: Platform;
  lang: Lang;
  /** Workspace flavor (D15) — renderers branch on person vs brand surfaces. */
  flavor: Flavor;
  /** Facts — passed through untouched from the profile. */
  identity: Identity;
  experience: ExperienceItem[];
  projects: Project[];
  publications: Publication[];
  skills: Skill[];
  /** Language-aware text, filtered by platform+lang. */
  bios: Bio[];
  headlines: Headline[];
  statement?: string;
  audiences: Record<string, string>;
  citationsGoal?: string;
  /** SEO set for this platform + GEO associations/claims. */
  keywords: { seo: string[]; geo: { associations?: string[]; claims?: string[] } };
  /** Brand blocks (v1.1/§17) — pass through untouched, lang-filtered where textual. */
  socialHandles: SocialHandle[];
  newsletter?: Newsletter;
  podcast?: Podcast;
  press: PressItem[];
  brandAudiences: Record<string, string>;
  /** User checks targeting this platform (platform `all` included). */
  checks: NonNullable<Profile["checks"]>;
  /** Evidence registry (v1.4/D17, §18) — facts, pass through untouched; renderers
   *  emit only `visibility: public` entries (§18.5). */
  credentials: Credential[];
  artifacts: Artifact[];
  active?: ActiveEntry;
  /** v1.6 (#103): the entity's structured-data identity — `@id`, `sameAs` and the
   *  entity fields, assembled ONCE in core (`structured-data.ts`). Renderers emit
   *  `jsonLd` verbatim and never re-derive it (the §18.9 credentialLdEntries precedent).
   *
   *  OPTIONAL on purpose (v1.6 review, F5): `compile()` always populates it, but the
   *  `PlatformProfile` seam is documented to accept hand-built slices, and a renderer
   *  must degrade (no structured data) rather than throw. Renderers therefore guard the
   *  whole chain — a required field guarded with `?.` would be a contract that lies. */
  structuredData?: StructuredDataReadiness;
  /** D22/§21: the resolved view — what this slice emits and what it omitted, with
   *  the reason for each omission. Present ONLY when the caller passed a selection
   *  policy; a policy-less compile stays byte-identical (no report key is added).
   *
   *  OPTIONAL for the same reason as `structuredData`: hand-built slices are a
   *  documented seam. */
  selection?: SelectionReport;
  /** Dot-paths of langMaps that fell back to `en` because `lang` was absent. */
  fallbacks: string[];
  /** Issue #102: the profile-completeness report for this slice, computed by
   *  `compile()` with the DEFAULT policy. OPTIONAL for the same reason as
   *  `structuredData` — a hand-built slice (the documented seam) may omit it,
   *  and the renderer degrades (no progress line) rather than throwing. The
   *  renderer emits the number verbatim; it NEVER recomputes it (the §18.9
   *  `credentialLdEntries` precedent). */
  completeness?: import("./completeness.js").CompletenessReport;
}
