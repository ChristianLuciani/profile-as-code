/**
 * pasco status — per-entry deploy-status report + ledger write path (D18, SPEC §19).
 *
 * Read mode: key · origin · surfaces · sync state (in-sync / stale / never) per
 *   trackable unit, plus untracked rows (no id) and removed ledger keys.
 * --mark <ledgerKey> <surface> [--at <iso>]: confirm a manual paste — the ONLY
 *   hand-triggered write to content/deployments.yaml (D14 write rule: only
 *   `pasco` mutates the ledger). Records the CURRENT contentHash → the unit goes
 *   in-sync until the SSOT changes again.
 * --write-checklist: regenerate CHECKLIST.md from the ledger (AUTO-GENERATED
 *   header) — the checklist is a VIEW of state pasco owns, not a second source
 *   of truth.
 *
 * Exit codes: 0 report/mark ok · 1 load or mark failure · 2 usage.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  type CompletenessReport,
  completeness,
  completenessLine,
  deployStatus,
  type LedgerReport,
  LoadError,
  type LoadedProfile,
  load,
  PLATFORMS,
  SchemaValidationError,
  trackableUnits,
} from "@profile-as-code/core";
import { parseDocument, stringify } from "yaml";
import { EXIT } from "../exit.js";
import { isJsonMode, line, report, section } from "../output.js";
import { type CompletenessPolicyConfig, sanitizeCompletenessPolicy } from "../workspace.js";

export interface StatusArgs {
  workspace: string;
  /** Surface to filter the report on — or the deployed surface in --mark mode. */
  platformArg?: string;
  /** --mark <ledgerKey>: confirm a deploy of that unit. */
  markKey?: string;
  /** --at <iso8601>: override the deployedAt timestamp (defaults to now). */
  markAt?: string;
  /** --write-checklist: regenerate CHECKLIST.md from the ledger. */
  writeChecklist?: boolean;
  /** --completeness: report the profile-completeness checklist (issue #102). */
  completeness?: boolean;
  /** The workspace policy from `.pascorc` (issue #102) — defaults to the shipped policy. */
  completenessPolicy?: CompletenessPolicyConfig;
}

const CHECKLIST_HEADER = `# CHECKLIST — deploy status

<!-- AUTO-GENERATED by \`pasco status --write-checklist\` (D18, SPEC §19) — do not edit by hand.
     Regenerate after every deploy confirm: pasco status --mark <ledgerKey> <surface>.
     Source of truth: content/deployments.yaml (only \`pasco\` mutates it). -->`;

function loadOrReport(args: StatusArgs): { profile: LoadedProfile } | { fail: number } {
  try {
    return { profile: load(args.workspace) };
  } catch (err) {
    if (err instanceof SchemaValidationError || err instanceof LoadError) {
      return {
        fail: report("status", false, EXIT.FAIL, {
          error: {
            kind: "load",
            message: err.message,
            ...(err instanceof SchemaValidationError ? { violations: [...err.issues] } : {}),
          },
        }),
      };
    }
    throw err;
  }
}

function markDeployed(args: StatusArgs, profile: LoadedProfile): number {
  const key = args.markKey as string;
  const surface = args.platformArg as string;

  if (!PLATFORMS.includes(surface as (typeof PLATFORMS)[number])) {
    return report("status", false, EXIT.USAGE, {
      error: {
        kind: "usage",
        message: `surface "${surface}" is not in the platform set (D16) — try one of: ${PLATFORMS.slice(0, 8).join(", ")}…`,
      },
    });
  }
  const matches = trackableUnits(profile).filter((u) => u.key === key);
  if (matches.length > 1) {
    // Write path upholds the same §19.2 invariant the read path enforces: never
    // persist a ledger state that load() would reject (premerge-review F2).
    return report("status", false, EXIT.FAIL, {
      error: {
        kind: "mark",
        message: `ambiguous ledger key "${key}" — ${matches.length} rows share this natural key; disambiguate (deduplicate or add unique ids) before marking (D18 §19.2)`,
      },
    });
  }
  const unit = matches[0];
  if (unit === undefined) {
    const isRemoved = profile.deployments[key] !== undefined;
    return report("status", false, EXIT.FAIL, {
      error: {
        kind: "mark",
        message: isRemoved
          ? `ledger key "${key}" is removed — the unit no longer exists in content/ (the ledger keeps the audit trail); recreate the entry or clean the key`
          : `unknown or untracked ledger key "${key}" — rows need a stable id to be trackable (D18 §19.2); run pasco status to list keys and untracked rows`,
      },
    });
  }
  let deployedAt = new Date().toISOString();
  if (args.markAt !== undefined) {
    const at = new Date(args.markAt);
    if (Number.isNaN(at.getTime())) {
      return report("status", false, EXIT.FAIL, {
        error: { kind: "mark", message: `--at "${args.markAt}" is not a valid ISO 8601 date-time` },
      });
    }
    deployedAt = at.toISOString();
  }

  const ledgerPath = join(args.workspace, "content", "deployments.yaml");
  let ledger: Record<string, Record<string, unknown>> = {};
  if (existsSync(ledgerPath)) {
    const doc = parseDocument(readFileSync(ledgerPath, "utf8"));
    if (doc.errors.length > 0) {
      return report("status", false, EXIT.FAIL, {
        error: {
          kind: "mark",
          message: `content/deployments.yaml: invalid YAML — ${doc.errors[0]?.message ?? "parse error"}`,
        },
      });
    }
    const node = doc.toJS({ maxAliasCount: 100 });
    if (node !== null && typeof node === "object")
      ledger = node as Record<string, Record<string, unknown>>;
  }
  const record = { deployedAt, contentHash: unit.hash, source: "manual" };
  ledger[key] = { ...(ledger[key] ?? {}), [surface]: record };
  writeFileSync(ledgerPath, stringify(ledger), "utf8");

  if (isJsonMode()) {
    return report("status", true, EXIT.OK, {
      data: { mode: "marked", key, surface, ...record, workspace: args.workspace },
    });
  }
  section("marked");
  line(`  ${key} → ${surface}: deployedAt ${deployedAt} · contentHash ${unit.hash.slice(0, 12)}…`);
  line(
    "  confirm the paste is live on the surface before running this (the ledger records the claim)",
  );
  return EXIT.OK;
}

function checklistBody(reportData: LedgerReport, completion: CompletenessReport): string {
  const fmt = (surfaces: Record<string, string>) =>
    Object.entries(surfaces)
      .sort()
      .map(([s, state]) => `${s} (${state})`)
      .join(", ");
  const stale = reportData.units.filter((u) => u.state === "stale");
  const inSync = reportData.units.filter((u) => u.state === "in-sync");
  const never = reportData.units.filter((u) => u.state === "never");
  const lines: string[] = [
    CHECKLIST_HEADER,
    "",
    // Issue #102: the completeness number rides the SAME generated view — it is
    // derived state (never stored) and the checklist is where the user looks.
    `Profile completeness: ${completenessLine(completion)}`,
    "",
  ];

  lines.push("## Pending — stale (SSOT changed after the last deploy)");
  if (stale.length === 0) lines.push("_None._");
  for (const u of stale) lines.push(`- [ ] \`${u.key}\` (${u.label}) — ${fmt(u.surfaces)}`);
  lines.push("", "## Never deployed");
  if (never.length === 0) lines.push("_None._");
  for (const u of never) lines.push(`- [ ] \`${u.key}\` (${u.label})`);
  lines.push("", "## In sync");
  if (inSync.length === 0) lines.push("_None._");
  for (const u of inSync) lines.push(`- [x] \`${u.key}\` (${u.label}) — ${fmt(u.surfaces)}`);
  lines.push("", "## Untracked (add an `id` to track)");
  if (reportData.untracked.length === 0) lines.push("_None._");
  for (const u of reportData.untracked) lines.push(`- ${u.block} — ${u.label}`);
  if (reportData.removed.length > 0) {
    lines.push("", "## Removed from content (ledger keeps the audit trail)");
    for (const r of reportData.removed)
      lines.push(`- \`${r.key}\` — was on: ${r.surfaces.join(", ")}`);
  }
  lines.push("");
  return lines.join("\n");
}

function completenessOf(args: StatusArgs, profile: LoadedProfile): CompletenessReport {
  return completeness(profile, sanitizeCompletenessPolicy(args.completenessPolicy));
}

/** `pasco status --completeness` — the checklist + percentage (issue #102). */
function runCompleteness(args: StatusArgs, profile: LoadedProfile): number {
  const result = completenessOf(args, profile);
  if (isJsonMode()) {
    return report("status", true, EXIT.OK, {
      data: {
        mode: "completeness",
        workspace: args.workspace,
        percent: result.percent,
        satisfied: result.satisfied,
        total: result.total,
        target: result.target,
        items: result.items,
      },
    });
  }
  section(`profile completeness — ${completenessLine(result)} (target: ${result.target})`);
  for (const item of result.items) {
    line(`  ${item.satisfied ? "[x]" : "[ ]"} ${item.label} — ${item.detail}`);
  }
  line("  → pasco status --write-checklist folds the number into CHECKLIST.md");
  return EXIT.OK;
}

export function runStatus(args: StatusArgs): number {
  if (args.markKey !== undefined && args.writeChecklist === true) {
    return report("status", false, EXIT.USAGE, {
      error: {
        kind: "usage",
        message:
          "usage: --mark and --write-checklist are mutually exclusive — run them sequentially",
      },
    });
  }
  if (args.completeness === true && args.markKey !== undefined) {
    return report("status", false, EXIT.USAGE, {
      error: {
        kind: "usage",
        message: "usage: --completeness and --mark are mutually exclusive — run them sequentially",
      },
    });
  }
  // Review of #205, F6: both flags are documented as alternatives, so accepting
  // them together and silently writing nothing was a lie. Reject explicitly.
  if (args.completeness === true && args.writeChecklist === true) {
    return report("status", false, EXIT.USAGE, {
      error: {
        kind: "usage",
        message:
          "usage: --completeness is a read-only report and --write-checklist writes CHECKLIST.md — run them separately (the generated view includes the completeness line)",
      },
    });
  }
  const loaded = loadOrReport(args);
  if ("fail" in loaded) return loaded.fail;
  const profile = loaded.profile;

  // Ledger write path (D14): --mark <key> <surface>.
  if (args.markKey !== undefined) return markDeployed(args, profile);

  const reportData = deployStatus(profile);
  const completion = completenessOf(args, profile);

  // Completeness report (issue #102): a standalone view of the same profile.
  if (args.completeness === true) return runCompleteness(args, profile);

  if (args.writeChecklist === true) {
    writeFileSync(
      join(args.workspace, "CHECKLIST.md"),
      checklistBody(reportData, completion),
      "utf8",
    );
    if (isJsonMode()) {
      return report("status", true, EXIT.OK, {
        data: {
          mode: "checklist-written",
          path: "CHECKLIST.md",
          ...summaryOf(reportData),
          completeness: {
            percent: completion.percent,
            satisfied: completion.satisfied,
            total: completion.total,
          },
        },
      });
    }
    line("CHECKLIST.md regenerated from content/deployments.yaml (AUTO-GENERATED view)");
    line(`  Profile completeness: ${completenessLine(completion)}`);
  }

  const filtered: LedgerReport =
    args.platformArg !== undefined
      ? {
          ...reportData,
          units: reportData.units.map((u) => {
            const onSurface = u.surfaces[args.platformArg as string];
            const state = onSurface === "in-sync" || onSurface === "stale" ? onSurface : "never";
            return {
              ...u,
              surfaces: onSurface === undefined ? {} : { [args.platformArg as string]: onSurface },
              state,
            };
          }),
        }
      : reportData;

  const data = {
    workspace: args.workspace,
    platform: args.platformArg ?? null,
    ...summaryOf(filtered),
    units: filtered.units,
    untracked: filtered.untracked,
    removed: filtered.removed,
  };
  if (isJsonMode()) return report("status", true, EXIT.OK, { data });

  const s = summaryOf(filtered);
  section(
    `deploy status — ${s.total} units · ${s.stale} stale · ${s.never} never · ${s.inSync} in-sync${args.platformArg !== undefined ? ` (surface: ${args.platformArg})` : ""}`,
  );
  const ordered = [...filtered.units].sort((a, b) => {
    const rank = { stale: 0, never: 1, "in-sync": 2 } as const;
    return rank[a.state] - rank[b.state] || a.key.localeCompare(b.key);
  });
  for (const u of ordered) {
    const surfaces =
      Object.keys(u.surfaces).length === 0
        ? "—"
        : Object.entries(u.surfaces)
            .sort()
            .map(([sf, st]) => `${sf} (${st})`)
            .join(", ");
    const origin = u.origin === "template" ? " [template]" : "";
    line(`  ${u.state.padEnd(8)} ${u.key.padEnd(36)} ${surfaces}${origin}`);
  }
  if (filtered.untracked.length > 0) {
    line("  untracked (add an id to track):");
    for (const u of filtered.untracked) line(`    ${u.block} — ${u.label}`);
  }
  if (filtered.removed.length > 0) {
    line("  removed from content (ledger keeps the audit trail):");
    for (const r of filtered.removed) line(`    ${r.key} — was on: ${r.surfaces.join(", ")}`);
  }
  line(
    "  → pasco status --mark <ledgerKey> <surface> confirms a paste; --write-checklist regenerates CHECKLIST.md",
  );
  return EXIT.OK;
}

function summaryOf(data: LedgerReport): {
  total: number;
  inSync: number;
  stale: number;
  never: number;
} {
  return {
    total: data.units.length,
    inSync: data.units.filter((u) => u.state === "in-sync").length,
    stale: data.units.filter((u) => u.state === "stale").length,
    never: data.units.filter((u) => u.state === "never").length,
  };
}
