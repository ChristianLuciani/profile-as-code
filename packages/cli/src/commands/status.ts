export interface StatusArgs {
  workspace: string;
  /** Surface to filter the report on — or the deployed surface in --mark mode. */
  platformArg?: string;
  /** --mark <ledgerKey>: confirm a deploy of that unit. */
  markKey?: string;
  /** --at <iso8601>: override the deployedAt timestamp (defaults to now). */
  markAt?: string;
  /** --write-checklist: regenerate CHECKLIST.md from the ledger. */
  writeChecklist?: boolean;
  /** --completeness: report the profile-completeness checklist (issue #102). */
  completeness?: boolean;
  /** --verify (§19.5, v1.10, issue #132): run the opt-in C1 live check AND write
   *  the ledger — `pasco`'s second ledger write trigger, after `--mark`. */
  verify?: boolean;
  /** The workspace policy from `.pascorc` (issue #102) — defaults to the shipped policy. */
  completenessPolicy?: CompletenessPolicyConfig;
  /** `.pascorc` `defaults.lang` — the lang the `--mark` anchor renders at, so the
   *  anchor matches what `pasco build` wrote (§19.5). NOTE: `pasco build --lang X`
   *  can persist an artifact at a non-default lang; see the `--mark` help text. */
  lang?: Lang;
  /** Fetch + the surface capabilities DECLARED for live checks (§19.5) — injected
   *  by tests; production resolves them per workspace (`verify.ts`). */
  deps?: Partial<StatusDeps>;
}

const CHECKLIST_HEADER = `# CHECKLIST — deploy status

<!-- AUTO-GENERATED by \`pasco status --write-checklist\` (D18, SPEC §19) — do not edit by hand.
     Regenerate after every deploy confirm: pasco status --mark <ledgerKey> <surface>.
     Source of truth: content/deployments.yaml (only \`pasco\` mutates it). -->`;

function loadOrReport(args: StatusArgs): { profile: LoadedProfile } | { fail: number } {
  try {
    return { profile: load(args.workspace) };
  } catch (err) {
    if (err instanceof SchemaValidationError || err instanceof LoadError) {
      return {
        fail: report("status", false, EXIT.FAIL, {
          error: {
            kind: "load",
            message: err.message,
            ...(err instanceof SchemaValidationError ? { violations: [...err.issues] } : {}),
          },
        }),
      };
    }
    throw err;
  }
}

/**
 * §19.5: the ANCHOR a `--mark` records — the SHA-256 of the canonical
 * `extractArtifact` projection of the artifact the engine would publish for
 * `surface`. It is rendered EXACTLY as `pasco build` renders it (same lang from
 * `.pascorc` `defaults.lang`, same `sanitizeCompletenessPolicy` completeness
 * policy, same `collectMedia` bundle), because the anchor must be the digest of
 * what the operator actually pasted — an approximation would read as permanent
 * out-of-band drift. The CALLER hashes; the renderer never does.
 *
 * Returns `undefined` — `attested` with NO anchor, the declared forward-only v1
 * limit — when the surface cannot be judged today. The capability is the ONE
 * authority on that (§19.5): no declaration (`no-extractor`), no derivable URL
 * (`no-artifact-url`) or a walled rung all mean `--verify` could never use an
 * anchor, so recording one would make `--mark` claim a judgeability it does not
 * have. No renderer, an empty render (`build` un-writes those) or a render that
 * throws are the same non-answer. NEVER a guessed digest.
 */
function artifactAnchor(
  args: StatusArgs,
  profile: LoadedProfile,
  surface: string,
  capability: SurfaceCapability | undefined,
): string | undefined {
  if (declaredReason(capability) !== undefined) return undefined;
  const extractor = capability?.extractor;
  const renderer = RENDERERS[surface];
  if (extractor === undefined || renderer === undefined) return undefined;
  // `pasco build` renders github-org only for a brand workspace: anchoring an
  // artifact the build never wrote would attest to a surface that does not exist.
  if (surface === "github-org" && profile.flavor !== "brand") return undefined;
  try {
    const policy = sanitizeCompletenessPolicy(args.completenessPolicy);
    const lang = args.lang ?? "en";
    const slice = compile(profile, surface as Platform, lang, policy);
    const result = renderer(slice, collectMedia(profile, args.workspace).assets);
    if (result.text === "") return undefined;
    return digestOf(extractor(result.text));
  } catch {
    return undefined;
  }
}

function markDeployed(args: StatusArgs, profile: LoadedProfile): number {
  const key = args.markKey as string;
  const surface = args.platformArg as string;

  if (!PLATFORMS.includes(surface as (typeof PLATFORMS)[number])) {
    return report("status", false, EXIT.USAGE, {
      error: {
        kind: "usage",
        message: `surface "${surface}" is not in the platform set (D16) — try one of: ${PLATFORMS.slice(0, 8).join(", ")}…`,
      },
    });
  }
  const matches = trackableUnits(profile).filter((u) => u.key === key);
  if (matches.length > 1) {
    // Write path upholds the same §19.2 invariant the read path enforces: never
    // persist a ledger state that load() would reject (premerge-review F2).
    return report("status", false, EXIT.FAIL, {
      error: {
        kind: "mark",
        message: `ambiguous ledger key "${key}" — ${matches.length} rows share this natural key; disambiguate (deduplicate or add unique ids) before marking (D18 §19.2)`,
      },
    });
  }
  const unit = matches[0];
  if (unit === undefined) {
    const isRemoved = profile.deployments[key] !== undefined;
    return report("status", false, EXIT.FAIL, {
      error: {
        kind: "mark",
        message: isRemoved
          ? `ledger key "${key}" is removed — the unit no longer exists in content/ (the ledger keeps the audit trail); recreate the entry or clean the key`
          : `unknown or untracked ledger key "${key}" — rows need a stable id to be trackable (D18 §19.2); run pasco status to list keys and untracked rows`,
      },
    });
  }
  let deployedAt = new Date().toISOString();
  if (args.markAt !== undefined) {
    const at = new Date(args.markAt);
    if (Number.isNaN(at.getTime())) {
      return report("status", false, EXIT.FAIL, {
        error: { kind: "mark", message: `--at "${args.markAt}" is not a valid ISO 8601 date-time` },
      });
    }
    deployedAt = at.toISOString();
  }

  const read = readLedger(args, "mark");
  if ("fail" in read) return read.fail;
  const { ledger } = read;

  // §19.5: the confirmation records the second dimension too — `attested` (the
  // human's assertion) PLUS the anchor (`artifactHash`) when the surface can
  // produce one. The anchor is rendered and extracted HERE, at confirmation
  // time: that is the only moment the engine can render the artifact it is
  // attesting to (§19.5 "the digest of what is being attested"). A surface that
  // cannot be judged today records `attested` with NO anchor — the declared
  // forward-only v1 limit — rather than a guessed digest.
  const capability = depsOf(args, profile).capabilities[surface];
  const anchor = artifactAnchor(args, profile, surface, capability);
  const certification = attestedRecord(anchor);
  const record = { deployedAt, contentHash: unit.hash, source: "manual", certification };
  ledger[key] = { ...(ledger[key] ?? {}), [surface]: record };
  persistLedger(args, ledger);

  if (isJsonMode()) {
    return report("status", true, EXIT.OK, {
      data: { mode: "marked", key, surface, ...record, workspace: args.workspace },
    });
  }
  section("marked");
  line(`  ${key} → ${surface}: deployedAt ${deployedAt} · contentHash ${unit.hash.slice(0, 12)}…`);
  line(
    certification.artifactHash !== undefined
      ? `  certification: attested (anchor ${certification.artifactHash.slice(0, 12)}… — --verify can judge this record)`
      : `  certification: attested (no anchor — ${declaredReason(capability) ?? "the artifact could not be rendered at confirmation"}; --verify will observe this record but cannot judge it)`,
  );
  line(
    "  confirm the paste is live on the surface before running this (the ledger records the claim)",
  );
  return EXIT.OK;
}

/** §19.5: the certification token a surface carries IN TEXT — never a bare
 *  `in-sync`, which would present a human assertion as a machine check.
 *  Exported because the `--verify` report prints the same token. */
export function certToken(certification: SurfaceCertification): string {
  return certification.reason === undefined
    ? certification.state
    : `${certification.state}: ${certification.reason}`;
}

/** §19.5: the per-surface token from a unit's certification rollup (or `—` when
 *  the unit has no record on that surface). */
function certOf(certification: UnitStatusCert, surface: string): string {
  const surfaceCert = certification?.surfaces[surface];
  return surfaceCert === undefined ? "—" : certToken(surfaceCert);
}

type UnitStatusCert = UnitStatus["certification"];

/** §19.5: surfaces of a unit, each carrying BOTH dimensions — staleness (the
 *  existing answer) and its certification token. */
function formatSurfacePairs(
  surfaces: Record<string, string>,
  certification: UnitStatusCert,
): string {
  const keys = Object.keys(surfaces).sort();
  if (keys.length === 0) return "—";
  return keys
    .map((surface) => `${surface} (${surfaces[surface]}/${certOf(certification, surface)})`)
    .join(", ");
}

function checklistBody(
  reportData: LedgerReport,
  completion: CompletenessReport,
  profile: LoadedProfile,
): string {
  // §19.5: the checklist is a VIEW of state pasco owns, so it carries the
  // certification dimension too — projected from the same read rule as the report.
  const certification = certificationMap(profile);
  const fmt = (u: LedgerReport["units"][number]): string =>
    formatSurfacePairs(u.surfaces, certification[u.key] ?? null);
  const stale = reportData.units.filter((u) => u.state === "stale");
  const inSync = reportData.units.filter((u) => u.state === "in-sync");
  const never = reportData.units.filter((u) => u.state === "never");
  const lines: string[] = [
    CHECKLIST_HEADER,
    "",
    // Issue #102: the completeness number rides the SAME generated view — it is
    // derived state (never stored) and the checklist is where the user looks.
    `Profile completeness: ${completenessLine(completion)}`,
    "",
  ];

  lines.push("## Pending — stale (SSOT changed after the last deploy)");
  if (stale.length === 0) lines.push("_None._");
  for (const u of stale) lines.push(`- [ ] \`${u.key}\` (${u.label}) — ${fmt(u)}`);
  lines.push("", "## Never deployed");
  if (never.length === 0) lines.push("_None._");
  for (const u of never) lines.push(`- [ ] \`${u.key}\` (${u.label})`);
  lines.push("", "## In sync");
  if (inSync.length === 0) lines.push("_None._");
  for (const u of inSync) lines.push(`- [x] \`${u.key}\` (${u.label}) — ${fmt(u)}`);
  lines.push("", "## Untracked (add an `id` to track)");
  if (reportData.untracked.length === 0) lines.push("_None._");
  for (const u of reportData.untracked) lines.push(`- ${u.block} — ${u.label}`);
  if (reportData.removed.length > 0) {
    lines.push("", "## Removed from content (ledger keeps the audit trail)");
    for (const r of reportData.removed)
      lines.push(`- \`${r.key}\` — was on: ${r.surfaces.join(", ")}`);
  }
  lines.push("");
  return lines.join("\n");
}

/** The rollup's own view of "who is fully certified" — the per-unit certificate,
 *  never derived from staleness (§19.5: the dimensions never borrow evidence). */
function certificationLineOf(reportData: LedgerReport): string {
  const withRecord = reportData.units.filter((u) => u.certification !== null);
  const certified = withRecord.filter(
    (u) => u.certification?.state === "verified" || u.certification?.state === "attested",
  );
  return `${certified.length}/${withRecord.length} recorded unit(s) certified`;
}

function completenessOf(args: StatusArgs, profile: LoadedProfile): CompletenessReport {
  return completeness(profile, sanitizeCompletenessPolicy(args.completenessPolicy));
}

/** `pasco status --completeness` — the checklist + percentage (issue #102). */
function runCompleteness(args: StatusArgs, profile: LoadedProfile): number {
  const result = completenessOf(args, profile);
  if (isJsonMode()) {
    return report("status", true, EXIT.OK, {
      data: {
        mode: "completeness",
        workspace: args.workspace,
        percent: result.percent,
        satisfied: result.satisfied,
        total: result.total,
        target: result.target,
        items: result.items,
      },
    });
  }
  section(`profile completeness — ${completenessLine(result)} (target: ${result.target})`);
  for (const item of result.items) {
    line(`  ${item.satisfied ? "[x]" : "[ ]"} ${item.label} — ${item.detail}`);
  }
  line("  → pasco status --write-checklist folds the number into CHECKLIST.md");
  return EXIT.OK;
}

/**
 * `pasco status` — synchronous for every mode EXCEPT `--verify`, which is async
 * because it performs the C1 live check (§19.5). Callers must await the result
 * (the CLI entry point does); every other path resolves immediately.
 */
export async function runStatus(args: StatusArgs): Promise<number> {
  if (args.markKey !== undefined && args.writeChecklist === true) {
    return report("status", false, EXIT.USAGE, {
      error: {
        kind: "usage",
        message:
          "usage: --mark and --write-checklist are mutually exclusive — run them sequentially",
      },
    });
  }
  // §19.5: `--verify` is a WRITE path (it records the evidence in the ledger) and
  // it fetches. Accepting it beside another write, or beside a pure read, would
  // mean one of the two was silently ignored — reject, like the existing pairs.
  if (args.verify === true && args.markKey !== undefined) {
    return report("status", false, EXIT.USAGE, {
      error: {
        kind: "usage",
        message:
          "usage: --verify and --mark are both ledger write paths — run them separately (--mark confirms a paste; --verify checks a live surface)",
      },
    });
  }
  if (args.verify === true && args.writeChecklist === true) {
    return report("status", false, EXIT.USAGE, {
      error: {
        kind: "usage",
        message:
          "usage: --verify writes the ledger and --write-checklist writes CHECKLIST.md — run them separately (regenerate the checklist after verifying)",
      },
    });
  }
  if (args.verify === true && args.completeness === true) {
    return report("status", false, EXIT.USAGE, {
      error: {
        kind: "usage",
        message:
          "usage: --verify is a live check and --completeness is a read-only report — run them separately",
      },
    });
  }
  if (args.completeness === true && args.markKey !== undefined) {
    return report("status", false, EXIT.USAGE, {
      error: {
        kind: "usage",
        message: "usage: --completeness and --mark are mutually exclusive — run them sequentially",
      },
    });
  }
  // Review of #205, F6: both flags are documented as alternatives, so accepting
  // them together and silently writing nothing was a lie. Reject explicitly.
  if (args.completeness === true && args.writeChecklist === true) {
    return report("status", false, EXIT.USAGE, {
      error: {
        kind: "usage",
        message:
          "usage: --completeness is a read-only report and --write-checklist writes CHECKLIST.md — run them separately (the generated view includes the completeness line)",
      },
    });
  }
  const loaded = loadOrReport(args);
  if ("fail" in loaded) return loaded.fail;
  const profile = loaded.profile;

  // Ledger write path (D14): --mark <key> <surface>.
  if (args.markKey !== undefined) return markDeployed(args, profile);

  // Ledger write path #2 (§19.5, v1.10): --verify [platform] — the C1 live check.
  if (args.verify === true) return await verifyStatus(args, profile);

  const reportData = deployStatus(profile);
  const completion = completenessOf(args, profile);

  // Completeness report (issue #102): a standalone view of the same profile.
  if (args.completeness === true) return runCompleteness(args, profile);

  if (args.writeChecklist === true) {
    writeFileSync(
      join(args.workspace, "CHECKLIST.md"),
      checklistBody(reportData, completion, profile),
      "utf8",
    );
    if (isJsonMode()) {
      return report("status", true, EXIT.OK, {
        data: {
          mode: "checklist-written",
          path: "CHECKLIST.md",
          ...summaryOf(reportData),
          completeness: {
            percent: completion.percent,
            satisfied: completion.satisfied,
            total: completion.total,
          },
        },
      });
    }
    line("CHECKLIST.md regenerated from content/deployments.yaml (AUTO-GENERATED view)");
    line(`  Profile completeness: ${completenessLine(completion)}`);
    line(`  Certification: ${certificationLineOf(reportData)}`);
  }

  const filtered = filterReport(reportData, args.platformArg);

  const data = reportDataOf(filtered, args);
  if (isJsonMode()) return report("status", true, EXIT.OK, { data });

  const s = summaryOf(filtered);
  section(
    `deploy status — ${s.total} units · ${s.stale} stale · ${s.never} never · ${s.inSync} in-sync${args.platformArg !== undefined ? ` (surface: ${args.platformArg})` : ""}`,
  );
  const ordered = [...filtered.units].sort((a, b) => {
    const rank = { stale: 0, never: 1, "in-sync": 2 } as const;
    return rank[a.state] - rank[b.state] || a.key.localeCompare(b.key);
  });
  for (const u of ordered) {
    const surfaces = formatSurfacePairs(u.surfaces, u.certification);
    const origin = u.origin === "template" ? " [template]" : "";
    line(`  ${u.state.padEnd(8)} ${u.key.padEnd(36)} ${surfaces}${origin}`);
  }
  if (filtered.untracked.length > 0) {
    line("  untracked (add an id to track):");
    for (const u of filtered.untracked) line(`    ${u.block} — ${u.label}`);
  }
  if (filtered.removed.length > 0) {
    line("  removed from content (ledger keeps the audit trail):");
    for (const r of filtered.removed) line(`    ${r.key} — was on: ${r.surfaces.join(", ")}`);
  }
  line(
    `  certification: ${certificationLineOf(filtered)} (surfaces carry staleness/certification)`,
  );
  line(
    "  → pasco status --mark <ledgerKey> <surface> confirms a paste; --verify [platform] runs the opt-in C1 live check; --write-checklist regenerates CHECKLIST.md",
  );
  return EXIT.OK;
}
