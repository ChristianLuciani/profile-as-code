/**
 * The scaffolded README is the first file a newcomer reads (#385), and it is a
 * published surface under rule 9 (`AGENTS.md`): it may only reference what its
 * reader can open — a workspace path that exists, a `pasco` command, or an
 * https URL. An engine-checkout path (`packages/cli/README.md`) or a path that
 * only exists inside the package (`schema/README.md`) is a maintainer artifact,
 * not something the scaffolded workspace contains.
 *
 * The walker is exercised twice: against both real templates (must be clean)
 * and against a seeded broken sample (must be caught). A walker that cannot
 * fail is not a signal.
 */

import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { afterAll, describe, expect, it } from "vitest";

const __dirname = dirname(fileURLToPath(import.meta.url));
const CLI = join(__dirname, "..", "dist", "index.js");

const roots: string[] = [];
function tempDir(): string {
  const dir = mkdtempSync(join(tmpdir(), "pasco-init-readme-"));
  roots.push(dir);
  return dir;
}
afterAll(() => {
  for (const dir of roots) rmSync(dir, { recursive: true, force: true });
});

function run(args: string[]): { code: number; stdout: string; stderr: string } {
  const res = spawnSync(process.execPath, [CLI, ...args], { encoding: "utf8", timeout: 15_000 });
  if (res.error !== undefined) throw res.error;
  return { code: res.status ?? -1, stdout: res.stdout ?? "", stderr: res.stderr ?? "" };
}

/** Command names `pasco --help` advertises — read offline, never fetched. */
function advertisedCommands(): Set<string> {
  const help = run(["--help"]).stdout;
  return new Set(
    [...help.matchAll(/^ {2}([a-z][a-z0-9:-]*)(?:\s|$)/gm)].map((match) => match[1] as string),
  );
}

/** True when `pattern` (a `/`-split path, `*` allowed per segment) matches under `root`. */
function globMatches(root: string, pattern: string): boolean {
  let frontier = [root];
  for (const segment of pattern.split("/").filter(Boolean)) {
    const segmentRe = new RegExp(
      `^${segment.replace(/[.+?^${}()|[\]\\]/g, "\\$&").replace(/\*/g, ".*")}$`,
    );
    const next: string[] = [];
    for (const current of frontier) {
      if (!existsSync(current)) continue;
      let entries: string[];
      try {
        entries = readdirSync(current);
      } catch {
        continue; // a file at this depth cannot have children
      }
      for (const entry of entries) {
        if (segmentRe.test(entry)) next.push(join(current, entry));
      }
    }
    frontier = next;
  }
  return frontier.length > 0;
}

/**
 * Every unresolved reference in `readme` for a workspace at `workspace`.
 *
 * Resolution classes: an https URL · a `pasco <command>` that `--help`
 * advertises · a workspace path that exists (glob allowed) · a directory the
 * README itself declares as generated by a later command (it cannot exist at
 * `init` time by design). Template placeholders (`<platform>`) are patterns,
 * not pointers, and are out of scope by class.
 */
function unresolvedReferences(readme: string, workspace: string, commands: Set<string>): string[] {
  const problems: string[] = [];
  const lines = readme.split("\n");

  for (const match of readme.matchAll(/\[[^\]]*\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
    const dest = match[1] as string;
    if (dest.startsWith("https://")) continue;
    if (dest.startsWith("#")) continue;
    if (dest.startsWith("http://")) {
      problems.push(`insecure link: ${dest}`);
    } else if (!existsSync(join(workspace, dest))) {
      problems.push(`link target does not exist in the workspace: ${dest}`);
    }
  }

  // File references written as plain prose, not only in backticks: the
  // scaffold's original defect (`see schema/README.md`) was plain text. URLs
  // and markdown link destinations are removed first so neither their host/path
  // nor an already-validated target looks like a second workspace path.
  for (const line of lines) {
    const prose = line.replace(/https?:\/\/\S+/g, " ").replace(/\]\([^)]*\)/g, "]");
    for (const match of prose.matchAll(
      /(?<![\w/.-])((?:[\w.-]+\/)*[\w.-]+\.(?:md|markdown|ya?ml|json|jsonl|txt|ts|js))(?![\w/.-])/g,
    )) {
      const token = match[1] as string;
      if (globMatches(workspace, token)) continue;
      problems.push(`path does not exist in the workspace: ${token}`);
    }
  }

  // A command block or shell example is still a reference the reader may run:
  // validate every line that starts with `pasco <command>`, including fenced
  // `sh` blocks (the scaffold's whole Workflow section).
  for (const match of readme.matchAll(/^\s*pasco\s+([a-z][a-z0-9:-]*)/gm)) {
    const command = match[1] as string;
    if (!commands.has(command)) problems.push(`unknown pasco command: pasco ${command}`);
  }

  // Tokenize line by line: a token's declaration (on any line that names it
  // with a `pasco` command) makes a not-yet-created directory a forward
  // reference instead of a broken pointer. A bare directory name (`variants/`)
  // is a layout label, not a workspace-relative path.
  for (const line of lines) {
    for (const match of line.matchAll(/`([^`]+)`/g)) {
      const token = (match[1] as string).trim();

      if (token === "pasco" || token.startsWith("pasco ")) {
        const command = token.split(/\s+/)[1];
        if (command !== undefined && !commands.has(command)) {
          problems.push(`unknown pasco command: ${token}`);
        }
        continue;
      }
      if (token.startsWith("https://")) continue;
      if (token.startsWith("http://")) {
        problems.push(`insecure URL: ${token}`);
        continue;
      }

      const pathish = token.includes("/") || token.startsWith(".");
      if (!pathish) continue;
      if (token.includes("<") || token.includes(">")) continue;
      if (token.endsWith("/") && !token.slice(0, -1).includes("/")) continue;

      if (globMatches(workspace, token)) continue;
      const declared = lines
        .filter((candidate) => candidate.includes(token))
        .some((candidate) => /\bpasco\s+[a-z][a-z0-9:-]*/.test(candidate));
      if (token.endsWith("/") && declared) continue;

      problems.push(`path does not exist in the workspace: ${token}`);
    }
  }

  return [...new Set(problems)];
}

function scaffold(flavor?: "brand"): { workspace: string; readme: string } {
  const dir = join(tempDir(), "ws");
  const args = flavor === undefined ? ["init", dir] : ["init", "--flavor", flavor, dir];
  const result = run(args);
  expect(result.code).toBe(0);
  return { workspace: dir, readme: readFileSync(join(dir, "README.md"), "utf8") };
}

describe("scaffolded README references (#385)", () => {
  const commands = advertisedCommands();

  it("the person template references only what the reader can open", () => {
    const { workspace, readme } = scaffold();
    expect(unresolvedReferences(readme, workspace, commands)).toEqual([]);
  });

  it("the brand template references only what the reader can open", () => {
    const { workspace, readme } = scaffold("brand");
    expect(unresolvedReferences(readme, workspace, commands)).toEqual([]);
  });

  // #386: the skills ship under the global package, outside the sandbox a
  // coding agent runs in. The scaffold must name the bridge, with a destination
  // inside the workspace, so the reader can copy and open them.
  function expectSkillsBridge(readme: string, workspace: string): void {
    const destinations = [...readme.matchAll(/`pasco skills:export ([^`\s]+)`/g)].map(
      (match) => match[1] as string,
    );
    expect(
      destinations.length,
      "the scaffolded README must announce `pasco skills:export <dir>`",
    ).toBeGreaterThan(0);
    for (const destination of destinations) {
      expect(destination).not.toContain("<");
      const inside = relative(workspace, resolve(workspace, destination));
      const escapes = inside === ".." || inside.startsWith(`..${sep}`) || isAbsolute(inside);
      expect(
        inside !== "" && !escapes,
        `destination must stay inside the workspace: ${destination}`,
      ).toBe(true);
    }
  }

  it("the person template announces the skills:export bridge", () => {
    const { workspace, readme } = scaffold();
    expectSkillsBridge(readme, workspace);
  });

  it("the brand template announces the skills:export bridge", () => {
    const { workspace, readme } = scaffold("brand");
    expectSkillsBridge(readme, workspace);
  });

  it("the bridge check accepts an in-workspace destination and catches escapes", () => {
    const workspace = tempDir();
    expect(() => expectSkillsBridge("`pasco skills:export out`", workspace)).not.toThrow();
    expect(() => expectSkillsBridge("`pasco skills:export ..foo`", workspace)).not.toThrow();
    expect(() => expectSkillsBridge("no bridge here", workspace)).toThrow();
    expect(() => expectSkillsBridge("`pasco skills:export <dir>`", workspace)).toThrow();
    expect(() => expectSkillsBridge("`pasco skills:export ../out`", workspace)).toThrow();
    expect(() => expectSkillsBridge("`pasco skills:export ./../out`", workspace)).toThrow();
  });

  it("the walker catches a workspace path that does not exist", () => {
    const workspace = tempDir();
    mkdirSync(join(workspace, "content"));
    writeFileSync(join(workspace, "content", "identity.yaml"), "identity: {}\n");
    const readme = [
      "- `content/*.yaml` — facts (see schema/README.md)",
      "",
      "See packages/cli/README.md for the full command reference.",
    ].join("\n");
    expect(unresolvedReferences(readme, workspace, commands)).toEqual([
      "path does not exist in the workspace: schema/README.md",
      "path does not exist in the workspace: packages/cli/README.md",
    ]);
  });

  it("the walker catches an unknown command in a fenced sh block", () => {
    const workspace = tempDir();
    const readme = ["```sh", "pasco frobnicate --now", "```", ""].join("\n");
    expect(unresolvedReferences(readme, workspace, commands)).toEqual([
      "unknown pasco command: pasco frobnicate",
    ]);
  });
});
