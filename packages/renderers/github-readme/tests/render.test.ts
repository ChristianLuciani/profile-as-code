describe('renderer github-readme (SPEC §15)', () => {
  it('renders the minimal fixture byte-for-byte (deterministic output)', () => {
    const profile = load(MINIMAL);
    const slice = compile(profile, 'github-readme', 'en');
    const out = render(slice);
    expect(out.text).toBe(EXPECTED);
    expect(out.assets).toBeUndefined();
    expect(out.text.endsWith('\n')).toBe(true);
  });

  it('is a pure function: two renders of the same slice are identical', () => {
    const profile = load(MINIMAL);
    const slice = compile(profile, 'github-readme', 'en');
    expect(render(slice).text).toBe(render(slice).text);
  });

  it('renders ES with es statement and en-fallback for langMaps without es', () => {
    const profile = load(MINIMAL);
    const slice = compile(profile, 'github-readme', 'es');
    const out = render(slice);
    expect(out.text).toContain('**Ingeniera de IA construyendo infraestructura soberana de IA para la educación.**');
    expect(out.text).not.toContain('### Sovereign AI infrastructure engineer'); // no es headline
    expect(out.text).toContain('**sovereign-agentic-hub**'); // project description es exists
  });

  it('omits empty sections (no projects / publications / skills)', () => {
    const profile = load(MINIMAL);
    const slice = { ...compile(profile, 'github-readme', 'en'), projects: [], publications: [], skills: [] };
    const out = render(slice);
    expect(out.text).not.toContain('## Projects');
    expect(out.text).not.toContain('## Publications');
    expect(out.text).not.toContain('## Skills');
    expect(out.text).toContain('## Links');
    expect(out.text).toContain('0 projects · 0 publications');
  });

  it('badges only for known identity platforms, in identity.links order', () => {
    const profile = load(MINIMAL);
    const slice = compile(profile, 'github-readme', 'en');
    const badges = render(slice)
      .text.split('\n')
      .find((l) => l.startsWith('[!['));
    expect(badges).toBeDefined();
    expect(badges!.match(/\[!\[/g)!.length).toBe(5); // github, linkedin, x, orcid, substack
    expect(badges).toContain('img.shields.io');
    expect(badges!.indexOf('GitHub')).toBeLessThan(badges!.indexOf('ORCID'));
  });
});

describe('renderer github-readme — evidence registry (v1.4/D17/§18)', () => {
  /** Build a slice with a registry from inline workspace files. */
  function registrySlice(files: Record<string, string>, lang: 'en' | 'es' = 'en') {
    const dir = mkdtempSync(join(tmpdir(), 'pasco-render-'));
    mkdirSync(join(dir, 'content'), { recursive: true });
    for (const [name, body] of Object.entries(files)) writeFileSync(join(dir, 'content', name), body, 'utf8');
    try {
      const profile = load(dir);
      return { slice: compile(profile, 'github-readme', lang), cleanup: () => rmSync(dir, { recursive: true, force: true }) };
    } catch (err) {
      rmSync(dir, { recursive: true, force: true });
      throw err;
    }
  }

  const FILES = {
    'identity.yaml': 'name: Elena Vasquez\nlinks:\n  - label: GitHub\n    url: https://github.com/elena\n',
    'credentials.yaml': `- id: cert-aws-ml
  kind: certificate
  title: AWS Certified ML - Specialty
  issuer: Amazon Web Services
  verifyUrl: https://aws.amazon.com/verify
  issued: '2024-05-01'
  expires: '2027-05-01'
  visibility: public
- id: cert-secret
  kind: certificate
  title: Secret Cert
  issuer: Secret Issuer
  visibility: private
`,
    'artifacts.yaml': `- id: reel-2025
  kind: showreel
  title: Reel 2025
  description:
    en: Selected work 2025.
  locator:
    url: https://vimeo.com/reel2025
  license: CC-BY-4.0
  visibility: public
- id: gallery-local
  kind: gallery
  title: Local Gallery
  locator:
    path: media/photos/2025
  visibility: public
`,
  };

  it('emits a compact registry section with public entries only (§18.5)', () => {
    const { slice, cleanup } = registrySlice(FILES);
    try {
      const out = render(slice);
      expect(out.text).toContain('## Credentials');
      expect(out.text).toContain('- **AWS Certified ML - Specialty** (certificate) — Amazon Web Services, 2024–2027 · [verify](https://aws.amazon.com/verify)');
      expect(out.text).not.toContain('Secret Cert'); // private never leaves the workspace
      expect(out.text).toContain('## Artifacts');
      expect(out.text).toContain('[vimeo.com](https://vimeo.com/reel2025)');
    } finally {
      cleanup();
    }
  });

  it('never emits a public URL for a path locator (capability matrix, §18.3/D14)', () => {
    const { slice, cleanup } = registrySlice(FILES);
    try {
      const out = render(slice);
      expect(out.text).toContain('- **Local Gallery** (gallery)');
      expect(out.text).not.toContain('media/photos/2025');
    } finally {
      cleanup();
    }
  });

  it('adds hasCredential (public credentials) to the inline JSON-LD (§18.9)', () => {
    const { slice, cleanup } = registrySlice(FILES);
    try {
      const out = render(slice);
      const json = out.text.split('```json')[1]!.split('```')[0]!;
      const parsed = JSON.parse(json) as { hasCredential?: { name: string }[] };
      expect(parsed.hasCredential).toEqual([{ name: 'AWS Certified ML - Specialty', url: 'https://aws.amazon.com/verify', awardedBy: { '@type': 'Organization', name: 'Amazon Web Services' }, validFrom: '2024-05-01', validThrough: '2027-05-01', '@type': 'EducationalOccupationalCredential' }]);
    } finally {
      cleanup();
    }
  });
});

describe('renderer github-readme — media pipeline (M8, §18.6)', () => {
  function mediaSlice(files: Record<string, string>) {
    const dir = mkdtempSync(join(tmpdir(), 'pasco-media-render-'));
    mkdirSync(join(dir, 'content'), { recursive: true });
    for (const [name, body] of Object.entries(files)) writeFileSync(join(dir, 'content', name), body, 'utf8');
    try {
      return { slice: compile(load(dir), 'github-readme', 'en'), cleanup: () => rmSync(dir, { recursive: true, force: true }) };
    } catch (err) {
      rmSync(dir, { recursive: true, force: true });
      throw err;
    }
  }

  const MEDIA = {
    'identity.yaml': 'name: Elena Vasquez\nlinks:\n  - label: GitHub\n    url: https://github.com/elena\n',
    'artifacts.yaml': `- id: reel-local
  kind: showreel
  title: Reel 2025
  locator:
    path: media/photos/reel-2025.mp4
  visibility: public
- id: gallery-remote
  kind: gallery
  title: Remote Gallery
  locator:
    url: https://vimeo.com/gallery
`,
  };

  /** The build's bundle, as the renderer receives it via opts.assets. */
  const BUNDLE = [
    { artifactId: 'reel-local', target: 'assets/reel-local/reel-2025.mp4', source: '/ws/media/photos/reel-2025.mp4', sha256: 'a'.repeat(64), bytes: 10, origin: 'workspace' as const },
  ];

  it('emits the deploy-relative link for a bundled path-locator artifact and declares the assets it referenced', () => {
    const { slice, cleanup } = mediaSlice(MEDIA);
    try {
      const out = render(slice, { assets: BUNDLE });
      expect(out.text).toContain('- **Reel 2025** (showreel) — [assets/reel-local/reel-2025.mp4](assets/reel-local/reel-2025.mp4)');
      expect(out.assets).toEqual(['assets/reel-local/reel-2025.mp4']);
      expect(out.text).not.toContain('media/photos'); // never a workspace-internal path
    } finally {
      cleanup();
    }
  });

  it('without a bundle entry the path locator stays link-free — byte-identical to M7 output (§18.3)', () => {
    const { slice, cleanup } = mediaSlice(MEDIA);
    try {
      const out = render(slice);
      expect(out.text).toContain('- **Reel 2025** (showreel)');
      expect(out.text).not.toContain('assets/reel-local');
      expect(out.assets).toBeUndefined();
    } finally {
      cleanup();
    }
  });

  it('url-locator artifacts are never declared as assets (they link verbatim, URL SSOT)', () => {
    const { slice, cleanup } = mediaSlice(MEDIA);
    try {
      const out = render(slice, { assets: BUNDLE });
      expect(out.assets).not.toContain('assets/gallery-remote');
      expect(out.text).toContain('https://vimeo.com/gallery');
    } finally {
      cleanup();
    }
  });

  it('is deterministic with assets: same input → same bytes', () => {
    const { slice, cleanup } = mediaSlice(MEDIA);
    try {
      const a = render(slice, { assets: BUNDLE });
      const b = render(slice, { assets: BUNDLE });
      expect(a).toEqual(b);
    } finally {
      cleanup();
    }
  });
});
