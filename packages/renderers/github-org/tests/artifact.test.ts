/**
 * Live-verification capability of the `github-org` surface (SPEC §19.5, issue
 * #132 Lane B / #212) — the brand sibling of `github-readme`, declaring the same
 * three things: the canonical projection, the fetch allowlist and the URL of the
 * live org README derived from the URL SSOT.
 *
 * Golden fixtures (committed, byte-exact): see the `github-readme` sibling for
 * the fixture contract — bare / chrome / edited / projection / digest.
 */

import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile, load, type Profile } from "@profile-as-code/core";
import { afterAll, describe, expect, it } from "vitest";
import { artifactUrl, extractArtifact, fetchHosts, render } from "../src/index.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const FIXTURES = join(__dirname, "fixtures", "artifact");

const fixture = (name: string): string => readFileSync(join(FIXTURES, name), "utf8");
const digestOf = (text: string): string =>
  createHash("sha256").update(extractArtifact(text), "utf8").digest("hex");

const tempDirs: string[] = [];
afterAll(() => {
  for (const dir of tempDirs) rmSync(dir, { recursive: true, force: true });
});

/** A brand workspace loaded through the real `load()` (D12 validation). */
function brandWorkspace(extra: Record<string, string> = {}): Profile {
  const dir = mkdtempSync(join(tmpdir(), "pasco-org-artifact-"));
  tempDirs.push(dir);
  const content = join(dir, "content");
  mkdirSync(content, { recursive: true });
  const files: Record<string, string> = {
    "flavor.yaml": "brand\n",
    "identity.yaml":
      "name: Topia Press\nmission:\n  en: High-epistemic essays moving from dystopia to utopia.\ntagline:\n  en: From dystopia to utopia — the newsletter\nlinks:\n  - platform: website\n    url: https://topia.press\n",
    ...extra,
  };
  for (const [name, body] of Object.entries(files)) writeFileSync(join(content, name), body);
  return load(dir);
}

describe("extractArtifact — canonical projection (§19.5)", () => {
  it("projects the published artifact to the byte-golden projection", () => {
    expect(extractArtifact(fixture("bare.md"))).toBe(fixture("projection.md"));
  });

  it("is chrome-invariant: a preamble and an appendix do not move the digest", () => {
    expect(extractArtifact(fixture("chrome.md"))).toBe(fixture("projection.md"));
    expect(digestOf(fixture("chrome.md"))).toBe(digestOf(fixture("bare.md")));
  });

  it("is transport-invariant: a BOM, CRLF endings and blank padding do not move it", () => {
    const decorated = `\uFEFF\r\n${fixture("bare.md").replace(/\n/g, "\r\n")}\r\n`;
    expect(extractArtifact(decorated)).toBe(fixture("projection.md"));
    expect(digestOf(decorated)).toBe(digestOf(fixture("bare.md")));
  });

  it("is idempotent over its own output", () => {
    for (const name of ["bare.md", "chrome.md", "edited.md", "projection.md"]) {
      const once = extractArtifact(fixture(name));
      expect(extractArtifact(once)).toBe(once);
    }
  });

  it("reports an edit INSIDE the artifact as a different digest (drift)", () => {
    expect(digestOf(fixture("edited.md"))).not.toBe(digestOf(fixture("bare.md")));
    expect(extractArtifact(fixture("edited.md"))).not.toBe(fixture("projection.md"));
  });

  it("does not confuse the sibling surface's footer for its own terminus", () => {
    // The `github-readme` footer is NOT this renderer's marker: the projection
    // must not truncate at it.
    const foreign =
      "# Topia Press\n\n<!-- generated by profile-as-code pasco build github-readme · 0 projects -->\n\ntail\n";
    expect(extractArtifact(foreign)).toContain("tail");
  });

  // The two adapters carry the same boundary logic either side of their own slug
  // (the same-class declaration of §19.5), so the two highest-value regressions
  // are pinned on BOTH surfaces: a fix applied to one file only would otherwise
  // leave the other silently mis-projecting.
  it("ignores an H1 inside the chrome preamble, and closes at the LAST footer (regressions)", () => {
    const chromeWithHeading = [
      "## Platform nav",
      "",
      "# Topia Press (platform chrome heading)",
      "",
      ...fixture("bare.md").split("\n"),
      "",
      "appendix chrome",
    ].join("\n");
    expect(extractArtifact(chromeWithHeading)).toBe(fixture("projection.md"));

    const embedded = [
      "# Topia Press",
      "",
      "```html",
      "<!-- generated by profile-as-code pasco build github-org x -->",
      "```",
      "",
      "ORIGINAL line",
      "",
      "<!-- generated by profile-as-code pasco build github-org · 1 claimed surface -->",
    ].join("\n");
    expect(digestOf(embedded.replace("ORIGINAL line", "EDITED line"))).not.toBe(digestOf(embedded));
  });

  it("render → extract → digest is byte-stable (golden digest fixture)", () => {
    const profile = brandWorkspace({
      "socialHandles.yaml":
        "- platform: github-org\n  handle: topiapress\n  status: claimed\n  url: https://github.com/topiapress\n",
    });
    const digest = digestOf(render(compile(profile, "github-org", "en")).text);
    expect(digest).toBe(readFileSync(join(FIXTURES, "org.digest"), "utf8").trim());
  });
});

describe("artifactUrl — derived from the URL SSOT (§15.4/§18.4)", () => {
  const ORG_URL = "https://raw.githubusercontent.com/topiapress/.github/HEAD/profile/README.md";

  it("derives the org profile-README raw URL from the claimed github-org handle", () => {
    const profile = brandWorkspace({
      "socialHandles.yaml":
        "- platform: github-org\n  handle: topiapress\n  status: claimed\n  url: https://github.com/topiapress\n",
    });
    expect(artifactUrl(profile)).toBe(ORG_URL);
  });

  it("accepts a bare handle with no url, and prefers a claimed row", () => {
    expect(
      artifactUrl(
        brandWorkspace({
          "socialHandles.yaml": "- platform: github-org\n  handle: topiapress\n  status: claimed\n",
        }),
      ),
    ).toBe(ORG_URL);
    expect(
      artifactUrl(
        brandWorkspace({
          "socialHandles.yaml":
            "- platform: github-org\n  handle: pendingone\n  status: pending\n- platform: github-org\n  handle: topiapress\n  status: claimed\n",
        }),
      ),
    ).toBe(ORG_URL);
  });

  it("ignores a PENDING handle row: it is not a deployed surface yet", () => {
    expect(
      artifactUrl(
        brandWorkspace({
          "socialHandles.yaml": "- platform: github-org\n  handle: topiapress\n  status: pending\n",
        }),
      ),
    ).toBeNull();
  });

  it("is null when the brand declares no GitHub org surface (no-artifact-url)", () => {
    expect(artifactUrl(brandWorkspace())).toBeNull();
  });

  it("derives from a declared github-org identity link too", () => {
    expect(
      artifactUrl(
        brandWorkspace({
          "identity.yaml":
            "name: Topia Press\nlinks:\n  - platform: github-org\n    url: https://github.com/topiapress\n",
        }),
      ),
    ).toBe(ORG_URL);
  });

  it("refuses a github-readme link: a sibling surface cannot name this one", () => {
    expect(
      artifactUrl(
        brandWorkspace({
          "identity.yaml":
            "name: Topia Press\nlinks:\n  - platform: github-readme\n    url: https://github.com/topiapress\n",
        }),
      ),
    ).toBeNull();
  });

  it("refuses a non-slug owner — a foreign URL never becomes an owner", () => {
    for (const row of [
      "- platform: github-org\n  handle: 'evil.com'\n  status: claimed\n  url: https://notgithub.com/topiapress\n",
      "- platform: github-org\n  handle: '..'\n  status: claimed\n",
      "- platform: github-org\n  handle: 'a/b'\n  status: claimed\n",
    ]) {
      expect(artifactUrl(brandWorkspace({ "socialHandles.yaml": row }))).toBeNull();
    }
  });

  it("only ever derives a URL inside the declared fetch allowlist", () => {
    const profile = brandWorkspace({
      "socialHandles.yaml":
        "- platform: github-org\n  handle: topiapress\n  status: claimed\n  url: https://github.com/topiapress\n",
    });
    const url = artifactUrl(profile);
    expect(url).not.toBeNull();
    expect(fetchHosts).toContain(new URL(url as string).hostname);
  });

  it("declares the raw host as its one-host v1 allowlist", () => {
    expect(fetchHosts).toEqual(["raw.githubusercontent.com"]);
  });
});
