describe('github-org renderer (brand flavor, §17)', () => {
  it('renders the org README byte-for-byte from a brand workspace', () => {
    const profile = load(brandWorkspace());
    const slice = compile(profile, 'github-org', 'en');
    expect(slice.flavor).toBe('brand');
    const { text } = render(slice, { lang: 'en' });
    expect(text).toBe(EXPECTED);
  });

  it('is deterministic: same input → same bytes', () => {
    const dir = brandWorkspace();
    const a = render(compile(load(dir), 'github-org', 'en'), { lang: 'en' }).text;
    const b = render(compile(load(dir), 'github-org', 'en'), { lang: 'en' }).text;
    expect(a).toBe(b);
  });

  it('es tagline/mission fall back to en (compile + render lang fallback)', () => {
    const profile = load(brandWorkspace());
    const { text } = render(compile(profile, 'github-org', 'es'), { lang: 'es' });
    expect(text).toContain('From dystopia to utopia'); // en fallback
  });

  it('never emits a URL that is not in the SSOT (identity.links + claimed socialHandles)', () => {
    const profile = load(brandWorkspace());
    const { text } = render(compile(profile, 'github-org', 'en'), { lang: 'en' });
    const urls = [...text.matchAll(/https?:\/\/[^\s)\]]+/g)]
      .map((m) => m[0])
      .map((u) => u.replace(/["',]+$/, '')); // JSON-LD block ends URLs with ", or ,
    for (const url of urls) {
      expect(
        url.startsWith('https://img.shields.io/') || // badge images are chrome, not surfaces
          url.startsWith('https://schema.org') || // JSON-LD @context
          url.startsWith('https://topia.press') ||
          url.startsWith('https://x.com/topiapress') ||
          url.startsWith('https://bsky.app/profile/topiapress') ||
          url.startsWith('https://topiapress.substack.com') ||
          url.startsWith('https://example.com/topia-launch'),
      ).toBe(true);
    }
  });
});

/** v1.5 (issue #71): the contact email is a fact — emitted in Links + JSON-LD, never in sameAs. */
describe('github-org contact email (v1.5, issue #71)', () => {
  function brandWorkspaceWithEmail(): string {
    const dir = brandWorkspace();
    const original = readFileSync(join(dir, 'content', 'identity.yaml'), 'utf8');
    writeFileSync(join(dir, 'content', 'identity.yaml'), `${original}\nemail: hello@topia.press\n`);
    return dir;
  }

  it('emits the email as a mailto: row in Links and as the jsonLd email property', () => {
    const { text } = render(compile(load(brandWorkspaceWithEmail()), 'github-org', 'en'), { lang: 'en' });
    expect(text).toContain('## Links');
    expect(text).toContain('- mailto:hello@topia.press');
    const json = JSON.parse(text.split('```json')[1]!.split('```')[0]!) as Record<string, unknown>;
    expect(json['email']).toBe('hello@topia.press');
    expect(JSON.stringify(json.sameAs)).not.toContain('mailto:');
  });

  it('omits the email row and jsonLd email when the workspace has none (pre-v1.5 byte-parity)', () => {
    const { text } = render(compile(load(brandWorkspace()), 'github-org', 'en'), { lang: 'en' });
    expect(text).not.toContain('mailto:');
    expect(text).not.toContain('"email"');
  });
});

/** §18.9 brand payoff: credentials render on Organization surfaces too (public only). */
describe('github-org JSON-LD hasCredential (D17, §18.9)', () => {
  function brandWorkspaceWithCredentials(credentialsYaml: string): string {
    const dir = brandWorkspace();
    writeFileSync(join(dir, 'content', 'credentials.yaml'), credentialsYaml);
    return dir;
  }

  it('emits hasCredential → EducationalOccupationalCredential for public credentials', () => {
    const profile = load(brandWorkspaceWithCredentials(`- id: iso-27001
  kind: certificate
  title: ISO 27001 Lead Implementer
  issuer: PECB
  verifyUrl: https://credly.com/iso-27001
  issued: '2025-03-01'
  visibility: public
`));
    const { text } = render(compile(profile, 'github-org', 'en'), { lang: 'en' });
    const jsonBlock = text.split('```json')[1]!.split('```')[0]!;
    const jsonLd = JSON.parse(jsonBlock) as { hasCredential?: unknown[] };
    expect(jsonLd.hasCredential).toEqual([
      { '@type': 'EducationalOccupationalCredential', name: 'ISO 27001 Lead Implementer', url: 'https://credly.com/iso-27001', awardedBy: { '@type': 'Organization', name: 'PECB' }, validFrom: '2025-03-01' },
    ]);
  });

  it('never emits non-public credentials (§18.5 — renderers emit only public)', () => {
    const profile = load(brandWorkspaceWithCredentials(`- id: internal-cert
  kind: certificate
  title: Internal Certification
  issuer: Internal
  visibility: private
`));
    const { text } = render(compile(profile, 'github-org', 'en'), { lang: 'en' });
    expect(text).not.toContain('hasCredential');
    expect(text).not.toContain('Internal Certification');
  });
});

describe('github-org CommonMark-safe destinations (issue #75)', () => {
  /** Brand fixture whose SSOT URLs carry parens/space — contract-legitimate
   *  (`$defs/url`: `^https?://` + `format: uri`, and `new URL()` keeps `(`/`)`
   *  in a pathname) but fatal for a raw CommonMark destination: the link ends at
   *  the first `)` or space. Every destination this renderer emits must pass
   *  `mdHref()` (issue #73's helper, shared via @profile-as-code/markdown). */
  function unsafeBrand(): string {
    const dir = mkdtempSync(join(tmpdir(), 'pasco-org-unsafe-'));
    tempDirs.push(dir);
    const content = join(dir, 'content');
    mkdirSync(content, { recursive: true });
    writeFileSync(join(content, 'flavor.yaml'), 'brand\n');
    writeFileSync(
      join(content, 'identity.yaml'),
      `name: Topia Press
logo: https://topia.press/logo (1).png
links:
  - platform: website
    label: Website
    url: https://topia.press
`,
    );
    writeFileSync(
      join(content, 'socialHandles.yaml'),
      `- platform: x
  handle: topiapress
  status: claimed
  url: https://x.com/topia (press)
`,
    );
    writeFileSync(
      join(content, 'newsletter.yaml'),
      `platform: substack
url: https://topiapress.substack.com/archive (2026)
name:
  en: Topia Press
`,
    );
    writeFileSync(
      join(content, 'podcast.yaml'),
      `title:
  en: Topia Radio
url: https://open.spotify.com/show (1)
rss: https://topia.press/feed (rss)
`,
    );
    writeFileSync(
      join(content, 'press.yaml'),
      `- outlet: Example Gazette
  title:
    en: Topia Press launches
  url: https://example.com/topia-launch (2026)
  date: 2026-08-18
`,
    );
    return dir;
  }

  function rendered(): string {
    return render(compile(load(unsafeBrand()), 'github-org', 'en')).text;
  }

  it('badges: BOTH destinations are encoded — the shields.io image src and the handle href', () => {
    // the brand URL's path is interpolated INTO the shields.io URL, so a raw
    // paren breaks the image destination too (the issue called only the href out)
    expect(rendered()).toContain(
      '[![X](https://img.shields.io/badge/X-x.com/topia%20%28press%29-000000?style=flat&logo=X&logoColor=white)](https://x.com/topia%20%28press%29)',
    );
  });

  it('newsletter: the SSOT url destination is encoded (the label keeps its parser form)', () => {
    expect(rendered()).toContain(
      '- **Topia Press** ([topiapress.substack.com/archive%20(2026)](https://topiapress.substack.com/archive%20%282026%29))',
    );
  });

  it('podcast: url and rss destinations are encoded', () => {
    const text = rendered();
    expect(text).toContain('  - [open.spotify.com/show%20(1)](https://open.spotify.com/show%20%281%29)');
    expect(text).toContain('  - RSS: [topia.press/feed%20(rss)](https://topia.press/feed%20%28rss%29)');
  });

  it('press: the mention destination is encoded (the label is constant)', () => {
    expect(rendered()).toContain('([link](https://example.com/topia-launch%20%282026%29))');
  });

  it('logo: the image destination is encoded', () => {
    expect(rendered()).toContain('![logo](https://topia.press/logo%20%281%29.png)');
  });

  it('the `## Links` rows stay plain text (they are not CommonMark destinations)', () => {
    // verified in #73/#75: `- ${url}` rows carry no destination to break
    expect(rendered()).toContain('- https://topia.press\n- https://x.com/topia (press)');
  });

  it('property: no emitted destination carries a raw space, control char or paren', () => {
    const text = rendered();
    const opened = (text.match(/\]\(/g) ?? []).length;
    const closed = (text.match(/\]\([^()\u0000-\u0020\u007F-\u009F]*\)/g) ?? []).length;
    expect(opened).toBeGreaterThan(0);
    expect(closed).toBe(opened); // a raw space/paren/control in any destination breaks the pairing
  });

  it('byte-parity: the safe brand fixture emits zero percent-encoding (the helper only fires on the unsafe set)', () => {
    // The module-level byte-for-byte test above proves the full output is
    // unchanged for a workspace with no `(`/`)`/space; this states the property
    // directly — mdHref is a no-op outside the unsafe set.
    const text = render(compile(load(brandWorkspace()), 'github-org', 'en')).text;
    expect(text).not.toContain('%20');
    expect(text).not.toContain('%28');
    expect(text).not.toContain('%29');
  });

  it('empty-string langMap values are absent, not present-empty: no ghost tagline/mission, newsletter name falls back to hostnamePath (issue #84)', () => {
    const dir = brandWorkspace();
    writeFileSync(
      join(dir, 'content', 'identity.yaml'),
      `name: Topia Press
logo: https://topia.press/logo.png
established: 2026-08-18
mission:
  en: ""
tagline:
  en: ""
links:
  - platform: website
    label: Website
    url: https://topia.press
`,
    );
    writeFileSync(join(dir, 'content', 'newsletter.yaml'), `platform: substack
url: https://topiapress.substack.com
name:
  en: ""
cadence: monthly
`);
    const text = render(compile(load(dir), 'github-org', 'en')).text;
    expect(text).not.toMatch(/^> /m); // ghost tagline blockquote gone
    expect(text.split('\n')).not.toContain('** **'); // ghost mission gone
    expect(text).toContain(
      '- **topiapress.substack.com** ([topiapress.substack.com](https://topiapress.substack.com)) · monthly',
    ); // hostnamePath fallback engages
  });

  it('empty-string cadence is absent, not present-empty: no trailing separator (issue #86, F2)', () => {
    const dir = brandWorkspace();
    writeFileSync(join(dir, 'content', 'newsletter.yaml'), `platform: substack
url: https://topiapress.substack.com
cadence: ""
`);
    const text = render(compile(load(dir), 'github-org', 'en')).text;
    // The row ends at the link — the ` · ` separator never renders for "" (byte-parity:
    // a populated cadence still renders, see the issue-#84 test above).
    expect(text.split('\n')).toContain(
      '- **topiapress.substack.com** ([topiapress.substack.com](https://topiapress.substack.com))',
    );
  });
});
