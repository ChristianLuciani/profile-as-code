/**
 * Renderer `github-org` (M6, brand flavor) — deterministic, byte-stable org
 * README from a brand PlatformProfile (compile() slice). Same input → same bytes.
 *
 * The fixture is a minimal brand workspace (flavor: brand) exercising every
 * renderer section: header/tagline/mission, claimed handle badges, newsletter,
 * podcast, press, audiences, JSON-LD Organization, footer.
 */

import { compile, load } from '@profile-as-code/core';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import { render } from '../src/index.js';

const tempDirs: string[] = [];
function brandWorkspace(): string {
  const dir = mkdtempSync(join(tmpdir(), 'pasco-org-'));
  tempDirs.push(dir);
  const content = join(dir, 'content');
  mkdirSync(content, { recursive: true });
  writeFileSync(join(content, 'flavor.yaml'), 'brand\n');
  writeFileSync(
    join(content, 'identity.yaml'),
    `name: Topia Press
logo: https://topia.press/logo.png
established: 2026-08-18
mission:
  en: High-epistemic essays moving from dystopia to utopia.
tagline:
  en: From dystopia to utopia — the newsletter
links:
  - platform: website
    label: Website
    url: https://topia.press
`,
  );
  writeFileSync(
    join(content, 'socialHandles.yaml'),
    `- platform: x
  handle: topiapress
  status: claimed
  url: https://x.com/topiapress
- platform: bluesky
  handle: topiapress
  status: claimed
  url: https://bsky.app/profile/topiapress
- platform: instagram
  handle: topiapress
  status: pending
`,
  );
  writeFileSync(
    join(content, 'newsletter.yaml'),
    `platform: substack
url: https://topiapress.substack.com
name:
  en: Topia Press
cadence: monthly
`,
  );
  writeFileSync(
    join(content, 'podcast.yaml'),
    `title:
  en: Topia Radio
status: planned
`,
  );
  writeFileSync(
    join(content, 'press.yaml'),
    `- outlet: Example Gazette
  title:
    en: Topia Press launches
  url: https://example.com/topia-launch
  date: 2026-08-18
`,
  );
  writeFileSync(
    join(content, 'audiences.yaml'),
    `readers:
  en: High-epistemic readers who want constructive futures.
`,
  );
  return dir;
}

afterAll(() => {
  for (const dir of tempDirs) rmSync(dir, { recursive: true, force: true });
});

