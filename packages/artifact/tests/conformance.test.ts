/**
 * The shared projection's own conformance run (#216): the swapped-in body
 * applied to the factory itself, so `projectArtifact`/`createArtifactExtractor`
 * and the harness cannot drift apart. Adapter suites run the same body against
 * their own `extractArtifact` and their committed fixtures.
 *
 * It also pins the promises the body leans on and the ones only this package can
 * check: `isArtifactExtractor` answers true for a function THIS package produced
 * and false for a hand-written one (that is what makes a future one-file
 * divergence fail CI), the bound surface is frozen, and — against the REAL
 * platform enum — a slug that extends another slug does not close the shorter
 * one's region (review F1).
 */
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { describeArtifactConformance } from "../src/conformance.js";
import { createArtifactExtractor, isArtifactExtractor, projectArtifact } from "../src/index.js";

const SURFACE = "artifact";
const SCHEMA = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "..",
  "..",
  "schema",
  "profile.schema.json",
);

const footerFor = (slug: string): string =>
  `<!-- generated by profile-as-code pasco build ${slug} · 1 project -->`;

/** A text whose ONLY terminus candidate is `slug`'s footer, followed by content
 *  that must survive if `slug` is not the extracting surface's own slug. */
const withTailAfter = (slug: string): string =>
  ["# Elena Vasquez", "", "body", "", footerFor(slug), "", "TAIL"].join("\n");

describe("packages/artifact — the canonical projection (#216)", () => {
  describeArtifactConformance({
    surface: SURFACE,
    extractArtifact: createArtifactExtractor(SURFACE),
  });

  describe("the factory is the only producer the body accepts", () => {
    it("brands a function it created, and only that", () => {
      const extractor = createArtifactExtractor(SURFACE);
      expect(isArtifactExtractor(extractor)).toBe(true);
      // A hand-written function that matches the projection byte-for-byte is
      // still a second implementation: the brand is identity, not behavior.
      const copied = (text: string): string => projectArtifact(text, SURFACE);
      expect(isArtifactExtractor(copied)).toBe(false);
      expect(isArtifactExtractor(undefined)).toBe(false);
      expect(isArtifactExtractor("extractArtifact")).toBe(false);
      expect(isArtifactExtractor({})).toBe(false);
    });

    it("binds the surface it was created for, and each surface gets its own function", () => {
      const readme = createArtifactExtractor("github-readme");
      const org = createArtifactExtractor("github-org");
      expect(readme.surface).toBe("github-readme");
      expect(org.surface).toBe("github-org");
      // Two bindings of ONE implementation: they are not the same function
      // object (the surface is the split), but neither is a re-implementation —
      // `isArtifactExtractor` is true for both, and each recognises only its own
      // terminus.
      expect(readme).not.toBe(org);
      expect(isArtifactExtractor(readme) && isArtifactExtractor(org)).toBe(true);
      const orgFooter = footerFor("github-org");
      expect(readme(orgFooter)).toContain("github-org");
      expect(org(orgFooter)).toBe(orgFooter);
    });

    it("freezes the bound surface (the type says readonly, so the value does)", () => {
      const extractor = createArtifactExtractor("github-readme");
      expect(() => {
        (extractor as { surface: string }).surface = "github-org";
      }).toThrow(TypeError);
      expect(extractor.surface).toBe("github-readme");
      expect(extractor(footerFor("github-org"))).toContain("github-org");
    });
  });

  describe("the terminus is the surface's OWN slug, never an extension of it", () => {
    it("does not close at a footer whose slug extends the surface (review F1, real enum pairs)", () => {
      const { enum: slugs } = (
        JSON.parse(readFileSync(SCHEMA, "utf8")) as {
          $defs: { platform: { enum: string[] } };
        }
      ).$defs.platform;
      const pairs: ReadonlyArray<readonly [string, string]> = slugs
        .filter((s) => slugs.some((other) => other !== s && other.startsWith(`${s}-`)))
        .map((s) => [s, slugs.find((other) => other.startsWith(`${s}-`)) as string] as const)
        // Sorted by the shorter slug, so the expectation does not depend on the
        // enum's declaration order.
        .sort(([a], [b]) => a.localeCompare(b));
      // The property is only meaningful while the contract HAS such pairs; if the
      // enum stops having any, this test must say so instead of passing vacuously.
      expect(pairs.map(([short, long]) => `${short}→${long}`)).toEqual([
        "instagram→instagram-standalone",
        "linkedin→linkedin-page",
      ]);

      for (const [short, long] of pairs) {
        const text = withTailAfter(long);
        expect(projectArtifact(text, short)).toContain("TAIL");
        expect(createArtifactExtractor(short)(text)).toContain("TAIL");
        // Control: the longer slug DOES close at its own footer.
        expect(projectArtifact(text, long)).not.toContain("TAIL");
      }
    });

    it("keeps every input the old `\\b` guard matched (no regression on the green paths)", () => {
      const slug = "artifact";
      // The terminator may be a space, EOL, or any non-word, non-hyphen char.
      for (const suffix of ["", " ", "\uFEFF", ".", "· x"]) {
        const text = `# H1\n\nbody\n\n<!-- generated by profile-as-code pasco build ${slug}${suffix} -->\n\ntail`;
        expect(projectArtifact(text, slug)).not.toContain("tail");
      }
      // ...and a word/hyphen continuation is NOT this surface's terminus.
      for (const suffix of ["x", "2", "-page"]) {
        const text = `# H1\n\nbody\n\n<!-- generated by profile-as-code pasco build ${slug}${suffix} -->\n\ntail`;
        expect(projectArtifact(text, slug)).toContain("tail");
      }
    });
  });

  describe("transport normalization (not exported: it is part of the projection)", () => {
    it("turns CRLF/CR into LF and strips a BOM wherever it sits", () => {
      const line = footerFor(SURFACE);
      const text = `\uFEFF# H1\r\n\r\n\uFEFFbody\rc\r\n\r\n${line}`;
      expect(projectArtifact(text, SURFACE)).toBe(`# H1\n\nbody\nc\n\n${line}`);
      // A trailing BOM is content, not transport: it survives the projection.
      expect(projectArtifact(`# H1\nbody\uFEFF`, SURFACE)).toBe("# H1\nbody\uFEFF");
    });

    it("is pure: the same input yields the same bytes", () => {
      const text = `# H1\n\nbody\n\n${footerFor(SURFACE)}\n`;
      expect(projectArtifact(text, SURFACE)).toBe(projectArtifact(text, SURFACE));
    });
  });
});
