/**
 * Deterministic property checks over the canonical projection (#216).
 *
 * The migration evidence that the shared home is byte-equivalent to the two
 * deleted copies was a THROWAWAY differential harness (the base-commit
 * implementations lifted verbatim, 42 structured cases + 40 000 fuzz
 * comparisons, 0 divergences — recorded in the PR). Keeping the deleted
 * implementations alive as reference code to re-run it would be dead weight, so
 * what stays is the durable half: the projection's invariants, checked over a
 * deterministic pseudo-random corpus (same seed → same texts on any machine), so
 * a future edit to the bound fails here even on inputs nobody thought to write
 * by hand.
 *
 * It is NOT a differential test: it asserts properties the rule must hold for
 * every input, not bytes copied from the old code.
 */
import { describe, expect, it } from "vitest";
import { projectArtifact } from "../src/index.js";

/** Deterministic LCG — a fixed corpus, not a source of flakiness. */
function rng(seed: number): () => number {
  let state = seed;
  return () => {
    state = (state * 1103515245 + 12345) & 0x7fffffff;
    return state / 0x7fffffff;
  };
}

const TEXTS = [
  "# Elena Vasquez",
  "## Section",
  "### Sub",
  "body",
  "**bold**",
  "```html",
  "```",
  "",
  "   ",
  "<!-- unrelated comment -->",
  "\uFEFF# BOM header",
  "# ",
  "#A",
];

const footerFor = (slug: string): string =>
  `<!-- generated by profile-as-code pasco build ${slug} · 1 project -->`;

const SURFACES = ["artifact", "a-hyphenated-surface"];

/** Assemble a text from `count` random lines (BOM only at line start, so the
 *  transport rule is exercised without inventing a mid-line BOM). */
function randomText(next: () => number, count: number): string {
  const lines: string[] = [];
  for (let i = 0; i < count; i += 1) {
    lines.push(TEXTS[Math.floor(next() * TEXTS.length)] as string);
  }
  return lines.join("\n");
}

describe("canonical projection — invariants over a deterministic corpus (#216)", () => {
  for (const surface of SURFACES) {
    const own = footerFor(surface);

    it(`[${surface}] is idempotent and transport-invariant`, () => {
      const next = rng(216216);
      for (let i = 0; i < 750; i += 1) {
        const text = `${randomText(next, 1 + Math.floor(next() * 10))}\n\n${own}\n`;
        const once = projectArtifact(text, surface);
        expect(projectArtifact(once, surface)).toBe(once);

        // Transport: CRLF instead of LF, a BOM parked at the start of every other
        // line, blank padding above and below. None of it is content.
        const decorated = `\uFEFF\r\n${text
          .split("\n")
          .map((line, index) => (index % 2 === 1 ? `\uFEFF${line}` : line))
          .join("\r\n")}\r\n`;
        expect(projectArtifact(decorated, surface)).toBe(once);
      }
    });

    it(`[${surface}] ignores chrome injected around it, including an H1 above`, () => {
      const next = rng(216216 + 1);
      for (let i = 0; i < 750; i += 1) {
        // The region opens with an H1 so the "last header above the terminus"
        // bound is exercised on both sides of the chrome.
        const region = [
          "# Elena Vasquez",
          "",
          randomText(next, 1 + Math.floor(next() * 8)),
          "",
          own,
        ].join("\n");
        const expected = projectArtifact(region, surface);
        const chromed = ["# Chrome heading", "", "preamble", "", region, "", "appendix"].join("\n");
        expect(projectArtifact(chromed, surface)).toBe(expected);
      }
    });

    it(`[${surface}] never lets a footer whose slug EXTENDS it close the region`, () => {
      const next = rng(216216 + 2);
      for (let i = 0; i < 750; i += 1) {
        const extended = footerFor(`${surface}-page`);
        const text = `${randomText(next, 1 + Math.floor(next() * 8))}\n\n${extended}\n\nTAIL`;
        // No own terminus in this text: the extended sibling's footer is INSIDE
        // the region, so nothing may be truncated at it.
        expect(projectArtifact(text, surface)).toContain("TAIL");
        expect(projectArtifact(text, surface)).toContain(extended);
      }
    });

    it(`[${surface}] refuses a non-slug surface`, () => {
      const next = rng(216216 + 3);
      for (const bad of ["", `${surface}-`, "-", "A B", "a--b", "Ünit"]) {
        expect(() => projectArtifact(randomText(next, 3), bad)).toThrow(/not a surface slug/);
      }
    });
  }
});
