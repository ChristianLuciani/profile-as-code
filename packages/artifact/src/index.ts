/**
 * The canonical artifact projection of SPEC §19.5 — the ONE home of the bound
 * (issue #216, follow-up of #212 / Lane B).
 *
 * §19.5's extractor is what decides whether a live artifact reads `verified` or
 * `out-of-band-drift`, and its two bounds were both wrong in the first submission
 * (#212): an H1 inside a chrome preamble opened the artifact, and a copy of the
 * footer literal inside the artifact closed it early and hid real drift. Two
 * adapters carrying the same boundary logic by copy means a fix applied to one
 * file leaves the other certifying under different rules — the exact drift the
 * engine exists to prevent. So the projection lives here once, and every
 * verifying adapter DELEGATES (`createArtifactExtractor`), never re-implements —
 * the `packages/paste` precedent (#150/#157), D5, AGENTS.md rule 7.
 *
 * The projection is GENERIC over the surface: the bound rule ("the engine-owned
 * region opens at the last header above its terminus and closes at the last
 * generated footer", §15.3) is identical for every markdown artifact the engine
 * renders; the only surface input is which generated footer is THIS surface's
 * terminus. Everything GitHub-specific — `fetchHosts`, the owner resolution and
 * the URL template — stays with the surface, in its adapter (surface knowledge,
 * not transport).
 *
 * Pure, offline, deterministic: no network, no clock, no randomness, no AI. The
 * CALLER hashes — the digest is SHA-256 of the projection's bytes and this module
 * never hashes (§19.5).
 */

/**
 * A projection bound to one surface's generated footer. Callable exactly like
 * the frozen `extractArtifact(text)` seam of #212, and carrying the surface slug
 * it recognised so a consumer (or a conformance test) can read the binding
 * without re-deriving it.
 */
export type ArtifactExtractor = ((text: string) => string) & { readonly surface: string };

/**
 * The one §15.3 header marker the bound looks for. Only `# ` (an H1) can open the
 * region: the engine emits `# <name>` first and nothing shallower.
 */
const H1 = /^# /;

/**
 * Every extractor this module ever produced. Identity, not shape: a hand-written
 * function in an adapter that happens to match the canonical projection on a
 * corpus is still a second implementation and must fail CI — `isArtifactExtractor`
 * is how the conformance body says "this is the shared one" (a forged brand is a
 * deliberate act; a copied boundary is the accident #216 removes).
 */
const CREATED = new WeakSet<ArtifactExtractor>();

/** Escape a surface slug so it can never be read as regex syntax. */
function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * The D16 platform-slug shape — the ONE input this generic projection takes.
 *
 * It is REFUSED loudly rather than mis-read, because every invalid form used to
 * fail silently in the direction §19.5 exists to prevent: `""` matched EVERY
 * surface's footer (the region closed at a stranger's terminus), a trailing
 * `-` matched nothing (the region was the whole text), and `"GitHub"` matched
 * nothing. A caller that passes a surface this package cannot bind is a bug at
 * the call site, not a verdict to report.
 */
const SURFACE_SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

function assertSurface(surface: string): void {
  if (!SURFACE_SLUG.test(surface)) {
    throw new Error(
      `not a surface slug (D16): ${JSON.stringify(surface)} — the generic projection must know whose generated footer bounds the region`,
    );
  }
}

/**
 * The renderer's OWN terminus marker for `surface` (§15.3: the generated
 * footer). A sibling surface's footer is NOT this one's terminus: a
 * `github-readme` footer inside a `github-org` artifact must not close the org
 * region early, or a real edit below it would be hidden.
 *
 * The trailing guard is `(?![\w-])`, NOT `\b`: `-` is not a word character, so
 * `\b` let a SHORTER slug's marker match an EXTENDED sibling's footer — with the
 * real enum, extracting `linkedin` would close at `linkedin-page`'s footer and
 * hide a real edit below it (the review F1 repro; `instagram`/
 * `instagram-standalone` is the second live pair). `(?![\w-])` keeps every input
 * the old `\b` matched and additionally refuses a `-`/word continuation.
 */
function footerMarker(surface: string): RegExp {
  return new RegExp(
    `^<!-- generated by profile-as-code pasco build ${escapeRegExp(surface)}(?![\\w-])`,
  );
}

/**
 * §19.5 transport normalization: how the bytes travelled, not what was deployed.
 *
 * A BOM is stripped wherever an editor parked it — not just at byte 0, where
 * stripping it once would make the projection non-idempotent — and CRLF/CR line
 * endings become LF before the bound is computed.
 *
 * NOT exported: normalizing transport is part of the projection, and a consumer
 * that did it separately could bound a different region than `projectArtifact` —
 * the divergence this package removes.
 */
function normalizeTransport(text: string): string[] {
  return text
    .replace(/\r\n?/g, "\n")
    .split("\n")
    .map((line) => line.replace(/^\uFEFF+/, ""));
}

/**
 * §19.5: the canonical projection of an artifact `surface` publishes — the
 * engine-owned region, with platform/transport chrome stripped. The projection is
 * what the ledger anchors and what a live fetch is compared against, so
 * decoration the engine did not deploy can never read as `out-of-band-drift`:
 *
 *   1. a BOM and CRLF/CR line endings are how the bytes travelled, not what was
 *      deployed;
 *   2. the artifact OPENS at the last header above its terminus and CLOSES at its
 *      LAST generated footer (§15.3) — a preamble injected above or an appendix
 *      appended below is outside the engine's region. Both bounds take the LAST
 *      match on purpose: an H1 inside a chrome preamble must not become the
 *      artifact's opening (that would pull chrome in and report FALSE drift), and
 *      a copy of the footer literal INSIDE the artifact (a fenced example) must
 *      not become its terminus (that would hide a real edit — a false `verified`,
 *      the one verdict §19.5 exists to prevent). DECLARED v1 limit: content a
 *      human adds outside the region is not part of the artifact and so is not
 *      judged; content inside it is, and an edit there is drift;
 *   3. blank padding is not content.
 *
 * Pure and idempotent: `projectArtifact(projectArtifact(t, s), s) ===
 * projectArtifact(t, s)`, so the digest of `extract(render(p))` is stable across
 * re-extraction.
 *
 * Throws on a `surface` that is not a D16 slug: a projection that cannot name
 * whose footer it recognises would silently judge the wrong region.
 */
export function projectArtifact(text: string, surface: string): string {
  assertSurface(surface);
  const lines = normalizeTransport(text);
  const terminus = footerMarker(surface);

  const footer = lines.findLastIndex((line) => terminus.test(line));
  const limit = footer === -1 ? lines.length - 1 : footer;
  const header = lines.findLastIndex((line, index) => index <= limit && H1.test(line));

  // A terminus with no header above it cannot bound a region: the markers
  // disagree, so the whole text is the projection rather than an empty slice.
  const bounded = header !== -1;
  const from = bounded ? header : 0;
  const to = bounded || footer === -1 ? limit : lines.length - 1;

  const artifact = lines.slice(from, to + 1);
  let first = 0;
  let last = artifact.length - 1;
  while (first <= last && artifact[first]?.trim() === "") first += 1;
  while (last >= first && artifact[last]?.trim() === "") last -= 1;
  return artifact.slice(first, last + 1).join("\n");
}

/**
 * Bind the canonical projection to one surface's generated footer — the ONE
 * thing a verifying adapter needs to export (`extractArtifact`), so a surface
 * cannot carry a second copy of the bound. The returned function is registered
 * with this module, which is what `isArtifactExtractor` verifies.
 *
 * `surface` is frozen (the type says `readonly`, so the value says it too): it is
 * the binding, and mutating it after construction would leave the extractor
 * matching a marker it no longer advertises.
 */
export function createArtifactExtractor(surface: string): ArtifactExtractor {
  assertSurface(surface);
  const extractor = Object.defineProperty(
    (text: string): string => projectArtifact(text, surface),
    "surface",
    { value: surface, enumerable: true },
  ) as ArtifactExtractor;
  CREATED.add(extractor);
  return extractor;
}

/**
 * True only for a function this module produced: the mechanical form of "the
 * adapter delegates the bound, it does not re-implement it". A future one-file
 * divergence (a hand-rolled `extractArtifact` in one adapter) is a second
 * implementation and fails the conformance body, before it can certify one
 * surface under rules the other does not share (#216).
 */
export function isArtifactExtractor(value: unknown): value is ArtifactExtractor {
  return (
    (typeof value === "function" || (typeof value === "object" && value !== null)) &&
    CREATED.has(value as ArtifactExtractor)
  );
}
