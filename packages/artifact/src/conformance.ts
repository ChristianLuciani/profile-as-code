/**
 * The shared artifact-projection conformance body (#216): ONE suite, run by
 * every verifying adapter against its own `extractArtifact`, so "this surface
 * projects the engine's region the canonical way" cannot drift per adapter.
 *
 * It ships as a subpath (`@profile-as-code/artifact/conformance`) consumed only
 * by tests, keeping the runtime entry free of the test tool — the
 * `packages/paste/conformance` precedent (#150/#157), and the same reason it
 * lives in a renderer support package and not in `core`.
 *
 * The body checks two different things, and both are load-bearing:
 *
 *   1. DELEGATION — the adapter's `extractArtifact` is a function this package
 *      produced (`isArtifactExtractor`) bound to the declared surface. A copied
 *      boundary in one adapter is a second implementation and fails here, before
 *      the two surfaces can certify the same artifact under different rules;
 *   2. the #212 regression set — boundary, transport and idempotence — run ONCE,
 *      generically over the surface, instead of once per adapter.
 */
import { describe, expect, it } from "vitest";
import {
  type ArtifactExtractor,
  createArtifactExtractor,
  isArtifactExtractor,
  projectArtifact,
} from "./index.js";

export interface ArtifactConformanceOptions {
  /** The surface slug the adapter publishes (D16) — its footer slug, and the ONE
   *  surface input the shared projection takes. */
  surface: string;
  /** The adapter's exported `extractArtifact` (the frozen #212 seam). */
  extractArtifact: (text: string) => string;
}

/** The engine-owned region of `surface`, as `pasco build` writes it: an H1, a
 *  body, and the surface's OWN generated footer last (§15.3). */
function region(surface: string, body: readonly string[] = BODY): string {
  return ["# Elena Vasquez", "", ...body, "", footer(surface, "1 project")].join("\n");
}

const BODY = [
  "### Sovereign AI infrastructure engineer",
  "",
  "**AI engineer building sovereign, open-source AI infrastructure for education.**",
];

const EDITED_BODY = [
  "### Sovereign AI infrastructure engineer",
  "",
  "**AI engineer building something else entirely.**",
];

/** The generated footer §15.3 emits for `surface` — the engine's terminus. */
const footer = (surface: string, detail: string): string =>
  `<!-- generated by profile-as-code pasco build ${surface} · ${detail} -->`;

/** A footer that is NOT this surface's: a sibling slug cannot close the region,
 *  or a real edit below it would be hidden. `foreign-<surface>` is deliberately
 *  not a prefix-extension of `surface`, so the terminus regex cannot match it. */
const foreignFooter = (surface: string): string =>
  `<!-- generated by profile-as-code pasco build foreign-${surface} · 1 project -->`;

/**
 * The texts the shared projection must answer to — the #212 regression set,
 * GENERIC over the surface, named by the property each one pins. Exported so a
 * consumer that must hold BOTH surfaces to the same rule (the CLI, whose
 * `--verify` certifies them) runs this corpus instead of a second one that could
 * drift.
 */
export interface ArtifactConformanceCorpus {
  /** The artifact as published. */
  readonly clean: string;
  /** Platform chrome: a preamble (carrying its own H1) above, an appendix below. */
  readonly chrome: string;
  /** Transport decoration: a BOM, CRLF endings and blank padding. */
  readonly transport: string;
  /** One body line changed INSIDE the region. */
  readonly edited: string;
  /** A copy of the footer literal inside the region, with an edit BELOW it. */
  readonly embeddedFooter: string;
  /** A foreign surface's footer, and NO own terminus. */
  readonly foreignFooter: string;
  /** No engine markers at all. */
  readonly markerless: string;
  /** Markers that disagree: a terminus above every header. */
  readonly inverted: string;
}

export function artifactConformanceCorpus(surface: string): ArtifactConformanceCorpus {
  const clean = region(surface);
  return {
    clean,
    chrome: [
      "<!-- platform preamble, outside the engine's region -->",
      "",
      '<p align="center"><img src="https://example.com/banner.svg" /></p>',
      "",
      "# Elena Vasquez (platform chrome heading)",
      "",
      ...clean.split("\n"),
      "",
      "appendix chrome",
    ].join("\n"),
    transport: `\uFEFF\r\n${clean.replace(/\n/g, "\r\n")}\r\n`,
    edited: region(surface, EDITED_BODY),
    embeddedFooter: [
      "# Elena Vasquez",
      "",
      "```html",
      footer(surface, "x"),
      "```",
      "",
      "ORIGINAL line",
      "",
      footer(surface, "1 project"),
    ].join("\n"),
    foreignFooter: ["# Elena Vasquez", "", foreignFooter(surface), "", "tail"].join("\n"),
    markerless: "\n\nplain text\n\n",
    inverted: `${footer(surface, "x")}\n# H1\n`,
  };
}

/**
 * Register the shared projection guarantee as a suite: delegation to the one
 * implementation, the bound (last header ↔ last own footer, both bounds taking
 * the LAST match), transport normalization (BOM anywhere, CRLF/CR, blank
 * padding), idempotence, and marker-disagreement fallbacks.
 */
export function describeArtifactConformance({
  surface,
  extractArtifact,
}: ArtifactConformanceOptions): void {
  describe(`shared artifact projection — ${surface}`, () => {
    const canonical: ArtifactExtractor = createArtifactExtractor(surface);
    const clean = region(surface);
    const corpus = artifactConformanceCorpus(surface);

    it("delegates the projection to the shared home instead of re-implementing it (#216)", () => {
      expect(isArtifactExtractor(extractArtifact)).toBe(true);
      expect((extractArtifact as ArtifactExtractor).surface).toBe(surface);
    });

    it("is the canonical projection on every corpus text (one implementation, not two)", () => {
      for (const text of Object.values(corpus)) {
        expect(extractArtifact(text)).toBe(canonical(text));
        expect(extractArtifact(text)).toBe(projectArtifact(text, surface));
      }
    });

    it("projects the published artifact to the engine-owned region", () => {
      expect(extractArtifact(corpus.clean)).toBe(clean);
    });

    it("is chrome-invariant: a preamble and an appendix do not move the projection", () => {
      expect(extractArtifact(corpus.chrome)).toBe(clean);
    });

    it("ignores an H1 inside the chrome preamble (regression: false drift)", () => {
      // The preamble above carries its own `# ` — taking the FIRST header would
      // pull chrome into the region and report drift on an untouched artifact.
      expect(extractArtifact(corpus.chrome)).toBe(clean);
    });

    it("is transport-invariant: a BOM, CRLF endings and blank padding do not move it", () => {
      expect(extractArtifact(corpus.transport)).toBe(clean);
    });

    it("reports an edit INSIDE the region as a different projection (drift)", () => {
      expect(extractArtifact(corpus.edited)).not.toBe(clean);
      expect(extractArtifact(corpus.edited)).toBe(region(surface, EDITED_BODY));
    });

    it("closes at the LAST own footer, so a footer literal inside cannot hide an edit (regression)", () => {
      // The fenced copy would close the region early — and the edit below it
      // would then never be compared, reading `verified` on a changed artifact.
      expect(extractArtifact(corpus.embeddedFooter)).toContain("ORIGINAL line");
      expect(
        extractArtifact(corpus.embeddedFooter.replace("ORIGINAL line", "EDITED line")),
      ).not.toBe(extractArtifact(corpus.embeddedFooter));
    });

    it("does not confuse a SIBLING surface's footer for its own terminus", () => {
      // No own terminus in this text, so nothing may be truncated at the foreign
      // marker — the foreign footer is INSIDE the region.
      expect(extractArtifact(corpus.foreignFooter)).toContain("tail");
      expect(extractArtifact(corpus.foreignFooter)).toContain(foreignFooter(surface));
    });

    it("does not require the engine's markers: a markerless text is trimmed whole", () => {
      expect(extractArtifact(corpus.markerless)).toBe("plain text");
      expect(extractArtifact("plain text")).toBe("plain text");
    });

    it("falls back to the whole text when the terminus precedes every header", () => {
      expect(extractArtifact(corpus.inverted)).toBe(corpus.inverted.replace(/\n$/, ""));
    });

    it("is idempotent over its own output", () => {
      for (const text of Object.values(corpus)) {
        const once = extractArtifact(text);
        expect(extractArtifact(once)).toBe(once);
      }
    });
  });
}
